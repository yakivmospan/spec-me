GENERATED = {"INDEX.md", "DECISIONS.md", "OPEN-QUESTIONS.md"}
# Markdown under `.specs/` that isn't a spec.
NOT_SPECS = GENERATED | {"README.md"}
# A manual test plan kept beside the spec it tests: `<spec>.manual-test-plan.md`.
TEST_PLAN_SUFFIX = ".manual-test-plan.md"

HEADER = """<!-- Generated by spec-rebuild-overviews — regenerate rather than edit; when this disagrees with the specs, the specs win. -->
<!-- Regenerate: python3 .agents/skills/spec-rebuild-overviews/scripts/build_index.py -->"""

# Open changes live here. Parsed by load_changes, never as specs.
CHANGES = "changes"
# A change's spec file, named after where it lands in `.specs/`: `specs.feature.logger.md`.
CHANGE_SPEC = re.compile(r"^specs\.(.+)\.md$")
STATUSES = ("draft", "approved", "merged")


@dataclass
class Decision:
    """One entry under a spec's `## Decisions`, parsed into its labelled sub-bullets.

    The shape is spec-style-rules' *What was rejected*'s: a bolded choice, then `Instead of` / `Because` /
    `Revisit when` / `Replaced {date}:` as sub-bullets. `instead_of` is the one that carries the
    information the code can't show — an entry missing it usually isn't a decision at all, which
    is why it's reported rather than quietly rendered blank.
    """
    text: str
    instead_of: str = ""
    because: str = ""
    revisit_when: str = ""
    replaced: str = ""
    replaced_date: str = ""


@dataclass
class OpenQuestion:
    text: str
    action: str
    resolved: bool = False


@dataclass
class Source:
    """One automated proof under `Verified:`: the test file it names, and the tests declared in it."""
    files: list[str]
    tests: list[str]


@dataclass
class Criterion:
    """One acceptance criterion: its id (`AC-3`), whether it's checked, and the proof it names."""
    ac_id: str
    checked: bool
    # Automated proofs: each `Source:` under `Verified:`.
    sources: list[Source] = field(default_factory=list)
    # A `Source: Manual` under `Verified:` — done by a person.
    manual: bool = False
    # Any `Source:`, automated or manual, nested under a `Verified:` sub-bullet.
    verified_sources: bool = False
    # Contract criteria this one implements, as (contract spec id or None, `AC-3`). None means
    # the prose wrote a bare `contract AC-3` and the target is resolved from `related`/`parent`.
    contract_refs: list[tuple[str | None, str]] = field(default_factory=list)

    @property
    def proven(self) -> bool:
        return bool(self.sources) or self.manual


@dataclass
class Spec:
    path: Path
    id: str
    title: str
    parent: str | None
    owns: list[str] = field(default_factory=list)
    related: list[str] = field(default_factory=list)
    updated: str = ""
    decisions: list[Decision] = field(default_factory=list)
    questions: list[OpenQuestion] = field(default_factory=list)
    criteria: list[Criterion] = field(default_factory=list)
    # `Currently violated:` lines under Constraints, as "constraint — violation".
    violations: list[str] = field(default_factory=list)
    # Change history rows too long to be one sentence, as "ticket date (n words)".
    long_history_rows: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------- parsing


def split_frontmatter(text: str) -> str | None:
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end == -1:
        return None
    return text[3:end]


def unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_frontmatter(block: str) -> dict[str, object]:
    """Minimal YAML: `key: scalar`, `key: [a, b]`, and block lists under `key:`."""
    data: dict[str, object] = {}
    current_key: str | None = None

    for raw in block.splitlines():
        line = re.sub(r"""^((?:[^#"']|"[^"]*"|'[^']*')*?)\s+#.*$""", r"\1", raw.rstrip())  # an inline `# comment`
        if not line.strip() or line.strip().startswith("#"):
            continue

        stripped = line.lstrip()
        indented = len(line) - len(stripped)

        if stripped.startswith("- ") and current_key and indented > 0:
            data.setdefault(current_key, [])
            target = data[current_key]
            if isinstance(target, list):
                target.append(unquote(stripped[2:]))
            continue

        if ":" not in stripped:
            continue

        key, _, value = stripped.partition(":")
        key = key.strip()
        value = value.strip()
        current_key = key

        if not value:
            data[key] = []
        elif value.startswith("[") and value.endswith("]"):
            inner = value[1:-1].strip()
            data[key] = [unquote(p) for p in inner.split(",") if p.strip()] if inner else []
        else:
            data[key] = unquote(value)

    return data


def as_list(value: object) -> list[str]:
    if isinstance(value, list):
        return [str(v) for v in value if str(v).strip()]
    if isinstance(value, str) and value.strip() and value.strip() != "[]":
        return [value.strip()]
    return []


def scalar(value: object) -> str:
    """A frontmatter value as a string; an empty `key:` parses as [] and reads as ""."""
    return value.strip() if isinstance(value, str) else ""


def parent_of(meta: dict[str, object]) -> str | None:
    parent = meta.get("parent")
    return None if parent in (None, "", "null", "~", []) else str(parent)


BOLD = re.compile(r"\*\*(.+?)\*\*", re.DOTALL)
AC_ID = re.compile(r"\*\*\s*(AC-\d+)\s*[:\]]?", re.IGNORECASE)
ACTION = re.compile(r"\*\*Action:\*\*\s*(.*)", re.DOTALL)
# `contract AC-2, AC-3` inside a criterion, optionally qualified (`contract.checkout's AC-1`) when
# the spec relates to more than one. Ranges ("AC-1 – AC-9") are deliberately not matched: a range
# in a criterion is a claim too vague to resolve, and goes unclaimed rather than half-understood.
CONTRACT_REF = re.compile(
    r"contract(?:\.([A-Za-z0-9._-]+?))?`?(?:'s)?\s+(AC-\d+(?:\s*(?:,|and)\s*AC-\d+)*)",
    re.IGNORECASE,
)
AC_PLAIN = re.compile(r"AC-\d+", re.IGNORECASE)
TICKED = re.compile(r"`([^`]+)`")
# A test function: `@Test`, or JUnit5's `@ParameterizedTest` or `@RepeatedTest`, any arguments or further
# annotations after it, then `fun` and its name, backticked or plain.
TEST_FUN = re.compile(
    r"@(?:Test|ParameterizedTest|RepeatedTest)\b(?:\([^)]*\))?(?:\s*@\w+(?:\([^)]*\))?)*\s*(?:(?:suspend|internal|public|override)\s+)*"
    r"fun\s+(`[^`]+`|\w+)"
)


def squash(text: str) -> str:
    """Collapse a multi-line markdown span into one line, dropping list/emphasis punctuation."""
    return " ".join(text.replace("~~", "").split()).strip(" —-–")


def body_after_frontmatter(text: str) -> str:
    if not text.startswith("---"):
        return text
    end = text.find("\n---", 3)
    return text[end + 4:] if end != -1 else text


def extract_section(body: str, heading: str) -> str:
    """The lines under a `## heading`, up to the next heading of the same or higher level."""
    lines = body.splitlines()
    wanted = heading.strip().lower()
    out: list[str] = []
    collecting = False

    for line in lines:
        if line.startswith("## "):
            if collecting:
                break
            collecting = line[3:].strip().lower() == wanted
            continue
        if line.startswith("# ") and collecting:
            break
        if collecting:
            out.append(line)

    return "\n".join(out)


def iter_entries(section: str) -> list[str]:
    """Top-level `- ` bullets, each joined with its indented continuation lines.

    A decision or an open question routinely wraps across several lines, and its bolded span can
    wrap with it — so entries have to be reassembled before anything can be matched against them.
    """
    entries: list[str] = []
    current: list[str] = []

    for line in section.splitlines():
        starts_entry = line.startswith("- ")
        if starts_entry:
            if current:
                entries.append("\n".join(current))
            current = [line[2:]]
        elif current and (not line.strip() or line.startswith((" ", "\t"))):
            current.append(line)
        elif current:
            entries.append("\n".join(current))
            current = []

    if current:
        entries.append("\n".join(current))

    return [e for e in entries if e.strip()]


SUBFIELD = re.compile(r"^\s+-\s*\*\*(.+?)\*\*\s*(.*)$")


def split_fields(entry: str) -> tuple[str, dict[str, str]]:
    """Split an entry into its headline and its labelled sub-bullets.

    Both the headline and a field's value can wrap across lines, so this tracks which one is
    currently open rather than assuming one line each.
    """
    head: list[str] = []
    fields: dict[str, str] = {}
    label: str | None = None
    buf: list[str] = []

    for line in entry.splitlines():
        match = SUBFIELD.match(line)
        if match:
            if label is not None:
                fields[label] = squash(" ".join(buf))
            label = match.group(1).strip().rstrip(":").lower()
            buf = [match.group(2)]
        elif label is not None:
            buf.append(line)
        else:
            head.append(line)

    if label is not None:
        fields[label] = squash(" ".join(buf))

    bold = BOLD.search("\n".join(head))
    headline = squash(bold.group(1)) if bold else squash("\n".join(head))
    return headline, fields


def parse_decisions(body: str) -> list[Decision]:
    out: list[Decision] = []
    for entry in iter_entries(extract_section(body, "Decisions")):
        text, fields = split_fields(entry)
        if not text:
            continue

        # `Replaced` carries its date inside the label (`**Replaced 2026-09-10:**`), so the key
        # varies per entry and can't be looked up directly.
        replaced_key = next((k for k in fields if k.startswith("replaced")), "")
        replaced_date = replaced_key[len("replaced"):].strip() if replaced_key else ""

        out.append(
            Decision(
                text=text,
                instead_of=fields.get("instead of", ""),
                because=fields.get("because", ""),
                revisit_when=fields.get("revisit when", ""),
                replaced=fields.get(replaced_key, "") if replaced_key else "",
                replaced_date=replaced_date,
            )
        )
    return out


def parse_open_questions(body: str) -> list[OpenQuestion]:
    out: list[OpenQuestion] = []
    for entry in iter_entries(extract_section(body, "Open questions")):
        stripped = entry.lstrip()
        if not stripped.startswith("["):
            continue
        resolved = stripped[:3].lower() == "[x]"
        match = BOLD.search(entry)
        text = squash(match.group(1)) if match else squash(stripped[3:])
        action_match = ACTION.search(entry)
        action = squash(action_match.group(1)) if action_match else ""
        if text:
            out.append(
                OpenQuestion(text=text, action=action, resolved=resolved)
            )
    return out


# A labelled sub-bullet with its indent kept. Proof nests `Source:` under `Verified:`, so it is read by
# depth — SUBFIELD, matching a label at any depth, would let nested labels overwrite each other.
FIELD_BULLET = re.compile(
    r"^(\s*)-\s*(?:\*\*(?P<bold>.+?)\*\*|(?P<plain>(?:verified|source):))\s*(?P<value>.*)$", re.IGNORECASE
)  # proof labels are read unbolded too, as a person may write them by hand


def field_label(match: re.Match[str]) -> str:
    return (match.group("bold") or match.group("plain")).strip().rstrip(":").strip().lower()


def block_end(lines: list[str], start: int, depth: int) -> int:
    """The index past the lines after `start` that are blank or indented deeper than `depth`."""
    end = start + 1
    while end < len(lines) and (not lines[end].strip() or len(lines[end]) - len(lines[end].lstrip()) > depth):
        end += 1
    return end


def ticked(text: str) -> list[str]:
    return [" ".join(t.split()) for t in TICKED.findall(text)]


def is_manual(value: str) -> bool:
    return value.strip().strip("`*_: ").lower().startswith("manual")


def read_verified(block: list[str], criterion: Criterion) -> None:
    """A `Verified:` sub-bullet: each nested `Source:` is a proof; anything else in it is ignored."""
    i = 0
    while i < len(block):
        match = FIELD_BULLET.match(block[i])
        label = field_label(match) if match else ""
        if label != "source" and not label.startswith("source:"):  # `**Source: Manual**` bolds the value too
            i += 1
            continue
        end = block_end(block, i, len(match.group(1)))
        criterion.verified_sources = True
        if is_manual(match.group("value")) or is_manual(label[len("source:"):]):
            criterion.manual = True  # what's nested under it is a description, never test names
        else:
            criterion.sources.append(Source(ticked(match.group("value")), ticked("\n".join(block[i + 1:end]))))
        i = end


def read_proof(entry: str, criterion: Criterion) -> str:
    """Read a criterion's proof into it, and return the rest of the entry — where its claims are.

    Test names and descriptions are left out of what's returned, so a `contract AC-n` inside one is
    never read as a claim.
    """
    lines = entry.splitlines()
    rest: list[str] = []
    i = 0
    while i < len(lines):
        match = FIELD_BULLET.match(lines[i])
        label = field_label(match) if match else ""
        if label != "verified" and not label.startswith("verified:"):
            rest.append(lines[i])
            i += 1
            continue
        end = block_end(lines, i, len(match.group(1)))
        read_verified(lines[i + 1:end], criterion)
        i = end
    return "\n".join(rest)


def parse_criteria(body: str) -> list[Criterion]:
    out: list[Criterion] = []
    for entry in iter_entries(extract_section(body, "Acceptance criteria")):
        stripped = entry.lstrip()
        if not stripped.startswith("["):
            continue
        id_match = AC_ID.search(entry)
        if not id_match:
            continue
        criterion = Criterion(
            ac_id=id_match.group(1).upper(),
            checked=stripped[:3].lower() == "[x]",
        )
        for ref in CONTRACT_REF.finditer(read_proof(entry, criterion)):
            target = f"contract.{ref.group(1)}" if ref.group(1) else None
            for ac in AC_PLAIN.findall(ref.group(2)):
                pair = (target, ac.upper())
                if pair not in criterion.contract_refs:
                    criterion.contract_refs.append(pair)
        out.append(criterion)
    return out


def parse_violations(body: str) -> list[str]:
    """`Currently violated:` sub-bullets under `## Constraints`, as "constraint — violation".

    A violation is the one line in a spec that goes false the moment someone fixes the code, and
    nothing about the fix points back at it — a spec edited after the code still looks fresh.
    Counting them in INDEX.md is what gets them re-read.
    """
    out: list[str] = []
    for entry in iter_entries(extract_section(body, "Constraints")):
        headline, fields = split_fields(entry)
        violation = fields.get("currently violated", "")
        if violation:
            out.append(f"{headline} — {violation}")
    return out


# spec-style-rules' *One row, one sentence*. Past this, a row is almost always a root-cause write-up or
# an investigation log rather than a statement of what changed.
HISTORY_ROW_WORDS = 35


def parse_long_history_rows(body: str) -> list[str]:
    """Change history rows whose Change cell runs past what one sentence needs.

    The style rule broken most often in practice, and the only one a word count can see.
    Informational: a long row misleads nobody, it taxes every reader.
    """
    out: list[str] = []
    for line in extract_section(body, "Change history").splitlines():
        if not line.strip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or set(cells[1]) <= set("-: ") or cells[1].lower() == "change":
            continue
        words = len(cells[1].split())
        if words > HISTORY_ROW_WORDS:
            out.append(f"{cells[0]} {cells[-1]} ({words} words)")
    return out


def load_specs(specs_dir: Path) -> tuple[list[Spec], list[str], list[str]]:
    """Every spec under `.specs/` outside `changes/`, plus (drift, warnings) found reading them."""
    specs: list[Spec] = []
    problems: list[str] = []
    warnings: list[str] = []

    for path in sorted(specs_dir.rglob("*.md")):
        if (path.name in NOT_SPECS or path.name.endswith(TEST_PLAN_SUFFIX)
                or path.relative_to(specs_dir).parts[0] == CHANGES):
            continue

        text = path.read_text(encoding="utf-8")
        block = split_frontmatter(text)
        rel = path.relative_to(specs_dir.parent).as_posix()

        if block is None:
            problems.append(f"{rel}: no frontmatter block — every spec needs one")
            continue

        meta = parse_frontmatter(block)
        missing = [k for k in ("id", "title") if not meta.get(k)]
        if missing:
            problems.append(f"{rel}: frontmatter missing required key(s): {', '.join(missing)}")
            continue
        status = scalar(meta.get("status"))
        if not status:
            warnings.append(f"{rel}: no status — add `status: merged`")
        elif status in ("draft", "approved"):
            warnings.append(f"{rel}: is `{status}` but sits outside changes/ — a spec in progress "
                            f"belongs in a change")
        elif status != "merged":
            warnings.append(f"{rel}: unknown status `{status}` — use `merged` outside changes/")

        spec_id = str(meta["id"])
        body = body_after_frontmatter(text)

        specs.append(
            Spec(
                path=path,
                id=spec_id,
                title=str(meta["title"]),
                parent=parent_of(meta),
                owns=as_list(meta.get("owns")),
                related=as_list(meta.get("related")),
                updated=scalar(meta.get("updated")),
                decisions=parse_decisions(body),
                questions=parse_open_questions(body),
                criteria=parse_criteria(body),
                violations=parse_violations(body),
                long_history_rows=parse_long_history_rows(body),
            )
        )

    return specs, problems, warnings


