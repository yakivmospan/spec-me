def glob_specificity(pattern: str) -> tuple[int, int]:
    """Higher sorts first. Fewer wildcards and more path segments = more specific."""
    return (-pattern.count("*") - 2 * pattern.count("**"), pattern.count("/"))


def iter_files(root: Path):
    """Yield every file under root, pruning SKIP_DIRS and dotdirs without descending into them."""
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for name in filenames:
            yield Path(dirpath) / name


def find_gaps(
    specs: list[Spec], repo_root: Path, extra: list[str], max_depth: int = 4
) -> list[str]:
    """Directories with zero spec coverage, found by actually checking which files match an
    `owns` glob — not by comparing directory name prefixes, which hides gaps nested under a
    directory that's only partially covered (e.g. `src/checkout/**` owned doesn't mean the rest
    of `src/` is; every sibling under `src/` needs checking individually).

    A directory with no coverage at all is reported and not descended into further (the whole
    subtree is the gap). A directory that's fully covered is skipped. A directory that's a mix
    gets descended into, to find exactly which subdirectories are the actual gap.
    """
    # `extra`: code an open change will own once its new spec exists — already routed, not a gap.
    owned_patterns = [p for s in specs for p in s.owns] + extra

    def covered(file_path: Path) -> bool:
        rel = file_path.relative_to(repo_root).as_posix()
        return any(fnmatch.fnmatch(rel, pat) for pat in owned_patterns)

    gaps: list[str] = []

    def classify(dir_path: Path, depth: int) -> None:
        rel_dir = dir_path.relative_to(repo_root).as_posix()
        all_files = list(iter_files(dir_path))
        if not all_files:
            return  # empty directory — nothing to own, nothing to report

        covered_count = sum(1 for f in all_files if covered(f))
        if covered_count == 0:
            gaps.append(f"'{rel_dir}/' has no owning spec yet")
            return
        if covered_count == len(all_files):
            return  # fully covered

        # Partially covered — descend to isolate the actual gap, unless we've gone deep enough
        # that further drilling stops being useful.
        if depth >= max_depth:
            gaps.append(f"'{rel_dir}/' is partially covered — check its subdirectories")
            return

        try:
            subdirs = sorted(
                e for e in dir_path.iterdir()
                if e.is_dir() and e.name not in SKIP_DIRS and not e.name.startswith(".")
            )
            loose_files = [e for e in dir_path.iterdir() if e.is_file()]
        except OSError:
            return

        for sub in subdirs:
            classify(sub, depth + 1)

        uncovered_loose = [f for f in loose_files if not covered(f)]
        if uncovered_loose:
            names = ", ".join(f.name for f in sorted(uncovered_loose)[:3])
            more = f" (+{len(uncovered_loose) - 3} more)" if len(uncovered_loose) > 3 else ""
            gaps.append(f"'{rel_dir}/' has uncovered file(s): {names}{more}")

    for child in sorted(repo_root.iterdir()):
        if child.is_dir() and not child.name.startswith(".") and child.name not in SKIP_DIRS:
            classify(child, 1)

    return gaps


TEST_DIRS = ("/src/test/", "/src/androidTest/", "/src/commonTest/", "/tests/", "/test/")

# Above this, two decisions in different specs are near-certainly the same decision written twice.
# Tuned to catch rewordings ("Version negotiation stays in X, not in the API module" vs
# "Version-negotiation semantics stay in X, not here") without flagging two decisions that merely
# discuss the same module.
DUPLICATE_RATIO = 0.6


def find_decision_problems(specs: list[Spec]) -> list[str]:
    """Decisions that aren't decisions, and decisions owned by two specs at once.

    Both are informational. "No `Instead of`" is a strong hint the entry is really a constraint or
    a scope note, but judging that needs a human read. Duplication is a similarity heuristic, and
    the fix (which spec should own it) is never mechanical.
    """
    import difflib

    out: list[str] = []
    flat = [(s, d) for s in specs for d in s.decisions]

    for spec, decision in flat:
        if not decision.instead_of:
            rel = spec.path.name
            out.append(
                f"{rel}: \"{decision.text[:70]}\" has no `Instead of` — if nothing was rejected, "
                f"this is a constraint or a scope note, not a decision"
            )

    for i, (spec_a, dec_a) in enumerate(flat):
        for spec_b, dec_b in flat[i + 1:]:
            if spec_a.id == spec_b.id:
                continue
            ratio = difflib.SequenceMatcher(None, dec_a.text.lower(), dec_b.text.lower()).ratio()
            if ratio >= DUPLICATE_RATIO:
                out.append(
                    f"same decision in two specs ({ratio:.0%} similar): `{spec_a.id}` and "
                    f"`{spec_b.id}` both state \"{dec_a.text[:60]}\" — one spec owns it, the "
                    f"other links"
                )

    return out


def test_files_under(owns: list[str], repo_root: Path) -> list[Path]:
    """Kotlin test files under a spec's `owns` globs."""
    files: set[Path] = set()
    for pattern in owns:
        # A trailing `**` matches files only from Python 3.13 on; `**/*` does everywhere.
        expanded = f"{pattern}/*" if pattern.endswith("**") else pattern
        for path in repo_root.glob(expanded):
            posix = path.as_posix()
            if (path.is_file() and path.suffix == ".kt" and "/build/" not in posix
                    and any(d in posix for d in TEST_DIRS)):
                files.add(path)
    return sorted(files)


def declared_tests(path: Path) -> set[str]:
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return set()
    return {" ".join(name.strip("`").split()) for name in TEST_FUN.findall(text)}


def listed_test_problems(criterion: Criterion, files: list[Path]) -> list[str]:
    """What in a criterion's automated Sources doesn't resolve against its spec's test files.

    A Source's file is named by file name or by a path suffix, and must match exactly one test file;
    each test under it must be declared in that file — not merely in some other Source's. A test
    renamed, moved or deleted in a refactor is the case this exists for — the spec keeps naming it,
    and nothing else would notice.
    """
    problems: list[str] = []
    for source in criterion.sources:
        if not source.files:
            problems.append("has a Source: naming no test file — backtick the file name, or write Source: Manual")
            continue

        resolved: list[Path] = []
        for name in source.files:
            matches = [f for f in files if f.as_posix().endswith("/" + name.lstrip("/"))]
            if not matches:
                problems.append(f"Source `{name}` is not a test file under the spec's `owns`")
            elif len(matches) > 1:
                problems.append(f"Source `{name}` matches {len(matches)} test files — give more of its path")
            else:
                resolved.extend(matches)
        if not resolved:
            continue

        declared = {path: declared_tests(path) for path in resolved}
        names = ", ".join(f"`{path.name}`" for path in resolved)
        for test in source.tests:
            hits = [path for path, tests in declared.items() if test in tests]
            if not hits:
                problems.append(f"test `{test}` is not declared in {names} — renamed, moved or deleted?")
            elif len(hits) > 1:
                problems.append(f"test `{test}` is declared in more than one Source file")
    return problems


def find_listed_test_problems(
    specs: list[Spec], changes: list[Change], repo_root: Path
) -> list[str]:
    """Proof that doesn't line up with its checkbox, and listed tests that don't resolve, in specs and in open changes — warnings only. A spec owning no code, like a contract, proves
    its criteria through the feature criteria naming them, so it's exempt from the no-proof check."""
    targets: list[tuple[str, list[str], list[Criterion]]] = [
        (spec.path.relative_to(repo_root).as_posix(), spec.owns, spec.criteria) for spec in specs
    ]
    targets += [
        (f"{change.path.relative_to(repo_root).as_posix()}/{spec.file}", spec.owns, spec.criteria)
        for change in changes for spec in change.specs
    ]
    out: list[str] = []
    for where, owns, criteria in targets:
        files: list[Path] | None = None
        for criterion in criteria:
            head = f"{where}: {criterion.ac_id}"
            if criterion.checked and owns and not criterion.proven:
                out.append(f"{head} is checked but names no proof — add a Source: under its Verified: (a test file, or Manual)")
            if not criterion.checked and criterion.verified_sources:
                hint = ", or leave it while its tests are still to be changed" if criterion.sources else ""
                out.append(f"{head} lists proof under Verified: but isn't checked — check it if the proof holds{hint}")
            if not criterion.sources:
                continue
            if not owns:
                out.append(f"{head} lists tests, but its spec owns no code to find them in")
                continue
            if files is None:
                files = test_files_under(owns, repo_root)
            out += [f"{head} {problem}" for problem in listed_test_problems(criterion, files)]
    return out


SPEC_CHECKS = Path(".agents") / ".cache" / "spec-checks.json"


def load_spec_checks(repo_root: Path) -> dict[str, dict]:
    """The last `spec-sync-with-code` run per spec id, recorded by its `record_check.py` — {} when there's none."""
    path = repo_root / SPEC_CHECKS
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def check_note(check: dict | None) -> str:
    """` — last checked 2026-09-14: tests 46/47 passed; differs: AC-5`, or "" with no check recorded."""
    if not isinstance(check, dict):
        return ""
    passed, failed = int(check.get("passed") or 0), int(check.get("failed") or 0)
    parts = [f"tests {passed}/{passed + failed} passed"] if passed + failed else ["no tests run"]
    if check.get("differs"):
        parts.append("differs: " + ", ".join(check["differs"]))
    if check.get("cant_tell"):
        parts.append("can't tell: " + ", ".join(check["cant_tell"]))
    if not check.get("differs") and not check.get("cant_tell"):
        parts.append("reading holds")
    return f" — last checked {check.get('date', '?')}: " + "; ".join(parts)


def find_stale(specs: list[Spec], repo_root: Path) -> list[str]:
    """Specs whose owned code has moved on since the spec last did.

    AGENTS.md opens with "specs hold intent, code holds behaviour, when they disagree stop and
    reconcile" — and nothing else in this toolchain could tell you they might. Everything else here
    checks a spec's structure. None of that notices a spec whose prose quietly stopped being true.

    `updated:` is read as "the day someone last confirmed this spec against its code", so the
    signal is commits to the owned globs dated after it. It's a prompt to look, never a failure:
    plenty of commits move code without moving intent, and a broad `owns` glob will surface often
    — which is itself worth knowing, since it usually means the spec is too broad or nobody has
    re-read it in a while. Returns [] when git can't answer, rather than guessing.
    """
    out: list[str] = []
    checks = load_spec_checks(repo_root)

    for spec in specs:
        if not spec.owns:
            continue
        note = check_note(checks.get(spec.id))
        rel = spec.path.relative_to(repo_root).as_posix()
        if not spec.updated:  # optional — nothing to judge staleness against
            continue

        command = [
            "git", "-C", str(repo_root), "log", "--format=%cd", "--date=short",
            # Strictly later days only: `updated:` has day granularity, so a spec confirmed the
            # same day as the commit it describes is current, not behind.
            f"--since={spec.updated} 23:59:59", "--",
            *(f":(glob){pattern}" for pattern in spec.owns),
        ]
        try:
            result = subprocess.run(command, capture_output=True, text=True, timeout=30)
        except (OSError, subprocess.SubprocessError):
            return out
        if result.returncode != 0:
            continue

        commits = [line for line in result.stdout.splitlines() if line.strip()]
        if commits:
            out.append(
                f"{rel}: {len(commits)} commit(s) to the code it owns since `updated: "
                f"{spec.updated}` (latest {commits[0]}) — `spec-sync-with-code` can confirm it{note}"
            )

    return out


def find_contract_problems(specs: list[Spec], changes: list[Change], repo_root: Path) -> list[str]:
    """Resolve every `(contract AC-n)` a criterion names, across specs and open changes — warnings only.

    A bare `contract AC-3` resolves against the spec's own `parent`/`related`, reading a spec in an
    open change where it has moved. What can't be resolved is reported rather than guessed at; so is
    a checked contract criterion whose implementing feature criterion is unchecked.
    """
    # (where, id, parent, related, owns, criteria) — specs first, then change files, which win by id.
    views = [(s.path.relative_to(repo_root).as_posix(), s.id, s.parent, s.related, s.owns, s.criteria)
             for s in specs]
    views += [(f"{c.path.relative_to(repo_root).as_posix()}/{s.file}", s.spec_id, s.parent, s.related,
               s.owns, s.criteria) for c in changes for s in c.specs if s.spec_id]
    latest = {view[1]: view for view in views}
    contracts = {i: v for i, v in latest.items() if not v[4] and v[5]}

    out: list[str] = []
    claims: dict[tuple[str, str], list[tuple[str, Criterion, bool]]] = {}
    for where, spec_id, parent, related, _owns, criteria in views:
        candidates = sorted({ref for ref in ([parent] if parent else []) + related if ref in contracts})
        for criterion in criteria:
            for target, ac_id in criterion.contract_refs:
                if target is None:
                    if len(candidates) != 1:
                        detail = ("no contract spec is in its `related`" if not candidates
                                  else f"several are ({', '.join(candidates)}) — qualify it")
                        out.append(f"{where}: {criterion.ac_id} names a bare `contract {ac_id}` but "
                                   f"{detail}")
                        continue
                    target = candidates[0]
                if target not in latest:
                    out.append(f"{where}: {criterion.ac_id} names `{target} {ac_id}`, which is not a "
                               f"known spec id")
                    continue
                claims.setdefault((target, ac_id), []).append((spec_id, criterion, "/changes/" in "/" + where))

    for where, spec_id, _parent, _related, owns, criteria in views:
        if owns or latest.get(spec_id, (where,))[0] != where:
            continue
        for criterion in criteria:
            if not criterion.checked:
                continue
            in_change = "/changes/" in "/" + where  # a current contract isn't judged by work in progress
            unchecked = [f"{i} {c.ac_id}" for i, c, from_change in claims.get((spec_id, criterion.ac_id), [])
                         if not c.checked and (in_change or not from_change)]
            if unchecked:
                out.append(f"{where}: {criterion.ac_id} is checked, but {', '.join(unchecked)} — which "
                           f"names it as implemented there — is not; confirmed by hand, that one is too")
    return out


def validate(
    specs: list[Spec], changes: list[Change], repo_root: Path
) -> tuple[list[str], list[str], list[str], list[str], list[str]]:
    """Returns (errors, warnings, gaps, decision_problems, stale).

    Errors are structural: a dangling glob, a duplicate id, a cycle, ambiguous ownership, a change
    spec file that can't land. These drive --check's exit code. Everything else is a warning or
    informational — gaps especially: "no spec here yet" is the normal state of most of a
    pre-existing codebase, and coverage grows one task at a time.
    """
    errors: list[str] = []
    by_id: dict[str, Spec] = {}

    for spec in specs:
        rel = spec.path.relative_to(repo_root).as_posix()
        if spec.id in by_id:
            other = by_id[spec.id].path.relative_to(repo_root).as_posix()
            errors.append(f"duplicate id '{spec.id}': {rel} and {other}")
        else:
            by_id[spec.id] = spec

    roots = [s for s in specs if s.parent is None]
    if len(roots) > 1:
        names = ", ".join(sorted(s.id for s in roots))
        errors.append(f"multiple root specs (parent: null): {names} — exactly one expected")
    if not roots and specs:
        errors.append("no root spec — one spec must have `parent: null`")

    # A spec moved into an open change is still a valid parent or related target.
    known = set(by_id) | {s.spec_id for c in changes for s in c.specs if s.spec_id}
    for spec in specs:
        rel = spec.path.relative_to(repo_root).as_posix()

        if spec.parent and spec.parent not in known:
            errors.append(f"{rel}: parent '{spec.parent}' is not a known spec id")

        # `related` is a real pointer, not decoration — a dangling one sends a reader to a spec
        # that was never written, or was renamed without this reference following.
        for ref in spec.related:
            if ref not in known:
                errors.append(f"{rel}: related '{ref}' is not a known spec id")

        # cycle detection
        seen, cursor = {spec.id}, spec.parent
        while cursor and cursor in by_id:
            if cursor in seen:
                errors.append(f"{rel}: parent chain forms a cycle at '{cursor}'")
                break
            seen.add(cursor)
            cursor = by_id[cursor].parent

        for pattern in spec.owns:
            if not any(repo_root.glob(pattern)):
                errors.append(f"{rel}: owns '{pattern}' matches nothing on disk")

    # overlapping globs of identical specificity
    claims: list[tuple[str, Spec]] = [(p, s) for s in specs for p in s.owns]
    for i, (pattern_a, spec_a) in enumerate(claims):
        for pattern_b, spec_b in claims[i + 1:]:
            if spec_a.id == spec_b.id:
                continue
            if glob_specificity(pattern_a) != glob_specificity(pattern_b):
                continue
            overlap = set(repo_root.glob(pattern_a)) & set(repo_root.glob(pattern_b))
            if overlap:
                errors.append(
                    f"ambiguous ownership: '{pattern_a}' ({spec_a.id}) and "
                    f"'{pattern_b}' ({spec_b.id}) both claim the same files at equal specificity"
                )

    # unowned source — a gap, not an error. See find_gaps' docstring.
    gaps = find_gaps(specs, repo_root, [p for c in changes for s in c.specs if s.new for p in s.owns])

    change_errors, warnings = validate_changes(changes, by_id, repo_root)
    errors.extend(change_errors)
    warnings += find_contract_problems(specs, changes, repo_root)
    warnings += find_listed_test_problems(specs, changes, repo_root)

    return errors, warnings, gaps, find_decision_problems(specs), find_stale(specs, repo_root)


