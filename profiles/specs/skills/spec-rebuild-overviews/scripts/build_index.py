ROOT_SPEC = re.compile(r"^\d\d-[^/]+\.md$")


def change_spec_rel(name: str) -> str:
    """`specs.feature.logger.md` → `feature/logger.md`: where a change's spec file lands in `.specs/`."""
    match = CHANGE_SPEC.match(name)
    return match.group(1).replace(".", "/") + ".md" if match else ""


@dataclass
class ChangeSpec:
    """One `specs.<path>.md` file in a change folder: the whole spec as it should read afterwards,
    landing at `.specs/<path>` (dots for slashes).

    `landing` is a spec still at that path — drift, since a change moves the spec it edits.
    """
    rel: str
    file: str
    spec_id: str = ""
    title: str = ""
    parent: str | None = None
    has_parent_key: bool = False
    status: str = ""
    owns: list[str] = field(default_factory=list)
    related: list[str] = field(default_factory=list)
    criteria: list[Criterion] = field(default_factory=list)
    decisions: list[Decision] = field(default_factory=list)
    questions: list[OpenQuestion] = field(default_factory=list)
    landing: Spec | None = None

    @property
    def new(self) -> bool:
        return self.landing is None

    @property
    def approved(self) -> bool:
        # `merged` in a change is past approval; validate_changes warns it should merge.
        return self.status in ("approved", "merged")

    def pending_decisions(self) -> list[Decision]:
        """Its decisions — only those the spec still at its place lacks, when one is (drift)."""
        if self.landing is None:
            return self.decisions
        have = {d.text.lower() for d in self.landing.decisions}
        return [d for d in self.decisions if d.text.lower() not in have]

    def pending_questions(self) -> list[OpenQuestion]:
        """Open questions this file adds, the same way as pending_decisions."""
        have = {q.text.lower() for q in self.landing.questions} if self.landing else set()
        return [q for q in self.questions if not q.resolved and q.text.lower() not in have]


@dataclass
class Task:
    title: str
    done: bool
    # Criterion ids from the task's trailing `[AC-3, AC-4]` tag, if any.
    tags: list[str] = field(default_factory=list)
    # Spec names the tag gives, as in `[contract AC-2]` or `[feature.logger AC-1]`.
    specs: list[str] = field(default_factory=list)


@dataclass(eq=False)
class Change:
    """A folder under `.specs/changes/` directly holding spec files, and an optional implementation plan."""
    path: Path
    name: str
    specs: list[ChangeSpec] = field(default_factory=list)
    tasks: list[Task] = field(default_factory=list)
    # The nearest enclosing change folder, when nested — for display only.
    parent: Change | None = field(default=None, repr=False)

    @property
    def approved(self) -> bool:
        return all(s.approved for s in self.specs)

    def status(self) -> str:
        done = sum(s.approved for s in self.specs)
        if done == len(self.specs):
            return "Approved"
        return "Draft" if done == 0 else f"Partly approved ({done}/{len(self.specs)})"

    def tasks_all_done(self) -> bool:
        return bool(self.tasks) and all(t.done for t in self.tasks)

    def link(self, specs_dir: Path) -> str:
        return self.path.relative_to(specs_dir).as_posix() + "/"


def parse_change_spec(path: Path, by_path: dict[str, Spec]) -> ChangeSpec:
    text = path.read_text(encoding="utf-8")
    meta = parse_frontmatter(split_frontmatter(text) or "")
    body = body_after_frontmatter(text)
    rel = change_spec_rel(path.name)
    spec_id = str(meta.get("id") or "")
    return ChangeSpec(
        rel=rel,
        file=path.name,
        spec_id=spec_id,
        title=str(meta.get("title") or ""),
        parent=parent_of(meta),
        has_parent_key="parent" in meta,
        status=scalar(meta.get("status")),
        owns=as_list(meta.get("owns")),
        related=as_list(meta.get("related")),
        criteria=parse_criteria(body),
        decisions=parse_decisions(body),
        questions=parse_open_questions(body),
        landing=by_path.get(rel),
    )


PLAN = "implementation-plan.md"
TASK_LINE = re.compile(r"^\d+\.\s+\[([ xX])\]\s+(.*)$")
TASK_TAG = re.compile(r"\[([^\[\]]*AC-\d+[^\[\]]*)\]\s*$", re.IGNORECASE)


def parse_tasks(change: Change, text: str) -> None:
    """Numbered checkboxes under `## Tasks`. A task's headline may wrap onto indented lines; its
    `- Check:` sub-bullets and `>` notes aren't part of it. Its tag is a trailing `[AC-3, AC-4]`."""
    body = body_after_frontmatter(text)
    section = extract_section(body, "Tasks") or body
    entries: list[tuple[bool, list[str]]] = []
    in_headline = False
    for line in section.splitlines():
        match = TASK_LINE.match(line)
        if match:
            entries.append((match.group(1).lower() == "x", [match.group(2)]))
            in_headline = True
        elif not in_headline:
            continue
        elif line.startswith((" ", "\t")) and line.strip() and not line.strip().startswith(("-", ">")):
            entries[-1][1].append(line.strip())
        else:
            in_headline = False
    for done, headline in entries:
        title = squash(" ".join(headline))
        tag = TASK_TAG.search(title)
        change.tasks.append(Task(
            title=title,
            done=done,
            tags=[t.upper() for t in AC_PLAIN.findall(tag.group(1))] if tag else [],
            specs=[n.lower() for n in re.findall(r"([A-Za-z][\w.-]*)\s+AC-\d+", tag.group(1))] if tag else [],
        ))


def load_change(folder: Path, root: Path, by_path: dict[str, Spec]) -> Change:
    change = Change(path=folder, name=folder.relative_to(root).as_posix())
    for path in sorted(p for p in folder.glob("specs.*.md") if p.is_file()):
        change.specs.append(parse_change_spec(path, by_path))
    plan = folder / PLAN
    if plan.is_file():
        parse_tasks(change, plan.read_text(encoding="utf-8"))
    return change


def load_changes(specs_dir: Path, specs: list[Spec]) -> tuple[list[Change], list[str]]:
    """Every open change, in folder order, plus warnings about change folders.

    A change is a folder directly holding at least one `specs.<path>.md`; any other folder only groups.
    """
    root = specs_dir / CHANGES
    if not root.is_dir():
        return [], []
    by_path = {s.path.relative_to(specs_dir).as_posix(): s for s in specs}
    changes: list[Change] = []
    warnings: list[str] = []

    def walk(folder: Path, enclosing: Change | None) -> None:
        current = enclosing
        rel = folder.relative_to(specs_dir.parent).as_posix()
        if folder != root and any(p.is_file() for p in folder.glob("specs.*.md")):
            current = load_change(folder, root, by_path)
            current.parent = enclosing
            changes.append(current)
        elif folder != root and (folder / PLAN).is_file():
            warnings.append(f"{rel}: no spec files yet — a change holds one `specs.<path>.md` per spec "
                            f"it touches")
        for sub in sorted(p for p in folder.iterdir() if p.is_dir()):
            walk(sub, current)

    walk(root, None)
    return changes, warnings


def validate_changes(
    changes: list[Change], by_id: dict[str, Spec], repo_root: Path
) -> tuple[list[str], list[str]]:
    """(drift, warnings) for open changes.

    Drift is only what stops a spec file from landing: a spec still at its place in `.specs/`, a
    path outside the tree, an unknown parent or related, a duplicate id.
    """
    errors: list[str] = []
    warnings: list[str] = []
    known = set(by_id) | {s.spec_id for c in changes for s in c.specs if s.spec_id}
    new_at: dict[str, list[tuple[str, str]]] = {}  # new spec id -> [(where, rel)]
    by_rel: dict[str, list[tuple[Change, ChangeSpec]]] = {}

    for change in changes:
        rel = change.path.relative_to(repo_root).as_posix()
        for spec in change.specs:
            where = f"{rel}/{spec.file}"
            if not spec.status:
                warnings.append(f"{where}: no status — add `status: draft`")
            elif spec.status == "merged":
                warnings.append(f"{where}: is `merged` but still in a change — merge it")
            elif spec.status not in STATUSES:
                warnings.append(f"{where}: unknown status `{spec.status}` — use `draft` or `approved`")
            if not spec.spec_id:
                errors.append(f"{where} has no `id:` — a spec file is the whole spec, id included")
                continue
            if not (spec.rel.startswith(("feature/", "contract/")) or ROOT_SPEC.match(spec.rel)):
                errors.append(f"{where} lands at .specs/{spec.rel}, which is not under feature/ or "
                              f"contract/, or a root spec")
            missing = [key for key, present in (("title", spec.title), ("parent", spec.has_parent_key))
                       if not present]
            if missing:
                warnings.append(f"{where} has no {' or '.join(f'`{k}:`' for k in missing)}")
            if spec.parent and spec.parent not in known:
                errors.append(f"{where}: parent '{spec.parent}' is not a known spec id")
            for ref in spec.related:
                if ref not in known:
                    errors.append(f"{where}: related '{ref}' is not a known spec id")
            ids = [c.ac_id for c in spec.criteria]
            for ac in sorted({a for a in ids if ids.count(a) > 1}):
                warnings.append(f"{where} lists {ac} twice")
            if spec.landing is not None:
                errors.append(f"{where}: .specs/{spec.rel} is still there — a change moves the spec it "
                              f"edits with `git mv`, never copies it")
            else:
                if spec.spec_id in by_id:
                    other = by_id[spec.spec_id].path.relative_to(repo_root).as_posix()
                    errors.append(f"duplicate id '{spec.spec_id}': {where} and {other}")
                new_at.setdefault(spec.spec_id, []).append((where, spec.rel))
            by_rel.setdefault(spec.rel, []).append((change, spec))

        # A story's plan and a module's plan may tag the enclosing contract's criteria too.
        known_acs: set[str] = set()
        known_ids: set[str] = set()
        cursor: Change | None = change
        while cursor is not None:
            known_acs |= {c.ac_id.upper() for s in cursor.specs for c in s.criteria}
            known_ids |= {s.spec_id.lower() for s in cursor.specs if s.spec_id}
            cursor = cursor.parent
        for task in change.tasks:
            if task.done:
                continue  # a ticked task's tags are history
            if task.specs and not any(i == n or i.startswith(n + ".") for n in task.specs for i in known_ids):
                continue  # the tag names a spec outside this change; its ids aren't this change's to judge
            for ac in task.tags:
                if ac not in known_acs:
                    warnings.append(f"{rel}: task \"{task.title[:60]}\" is tagged {ac}, which no spec "
                                    f"file in the change has")

    for spec_id, entries in sorted(new_at.items()):
        if len({r for _, r in entries}) > 1:
            errors.append(f"duplicate id '{spec_id}': {' and '.join(w for w, _ in entries)}")

    for rel, holders in sorted(by_rel.items()):
        if len(holders) < 2:
            continue
        names = " and ".join(f"`{c.name}`" for c, _ in holders)
        warnings.append(f"{names} both hold .specs/{rel} — fold one in first, then move it into the other")
    return errors, warnings


def spec_file_link(change: Change, spec: ChangeSpec, specs_dir: Path) -> str:
    return (change.path / spec.file).relative_to(specs_dir).as_posix()


def change_label(change: Change) -> str:
    """Top-level changes by name; a nested one by its path under the change enclosing it, indented."""
    if change.parent is None:
        return f"`{change.name}`"
    depth, cursor = 0, change.parent
    while cursor is not None:
        depth, cursor = depth + 1, cursor.parent
    return "&nbsp;&nbsp;" * (depth - 1) + f"↳ `{change.path.relative_to(change.parent.path).as_posix()}`"


def render_pending(changes: list[Change], specs_dir: Path) -> str:
    if not changes:
        return "_No open changes._"
    out = [
        "Work being written or agreed that `.specs/` doesn't show yet. Before editing code a listed "
        "spec owns, read its spec file in the change; its `implementation-plan.md` only when building "
        "the change. Status comes from each spec file's `status:`; Checked counts the criteria someone has "
        "confirmed, across the change's spec files.",
        "",
        "| Change | Status | Specs | Checked | Tasks done |",
        "|---|---|---|---|---|",
    ]
    for change in changes:
        spec_cells = ", ".join(
            f"[`{s.spec_id or s.file}`]({spec_file_link(change, s, specs_dir)})"
            for s in change.specs
        ) or "—"
        criteria = [c for s in change.specs for c in s.criteria]
        checked = f"{sum(c.checked for c in criteria)}/{len(criteria)}" if criteria else "—"
        done = f"{sum(t.done for t in change.tasks)}/{len(change.tasks)}" if change.tasks else "—"
        out.append(
            f"| [{change_label(change)}]({change.link(specs_dir)}) | {change.status()} | "
            f"{spec_cells} | {checked} | {done} |"
        )
    return "\n".join(out)


