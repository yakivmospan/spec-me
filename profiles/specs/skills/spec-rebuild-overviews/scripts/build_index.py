def render_tree(specs: list[Spec], specs_dir: Path) -> str:
    # Links are relative to specs_dir, not repo_root: INDEX.md lives inside specs_dir, and a
    # markdown relative link resolves against the file that contains it, not the repo root.
    by_parent: dict[str | None, list[Spec]] = {}
    for spec in specs:
        by_parent.setdefault(spec.parent, []).append(spec)

    lines: list[str] = []

    def walk(parent: str | None, depth: int) -> None:
        for spec in sorted(by_parent.get(parent, []), key=lambda s: s.path.name):
            rel = spec.path.relative_to(specs_dir).as_posix()
            lines.append(f"{'  ' * depth}- [`{spec.id}`]({rel}) — {spec.title}")
            walk(spec.id, depth + 1)

    walk(None, 0)

    known = {s.id for s in specs}
    orphans = [s for s in specs if s.parent and s.parent not in known]
    for spec in orphans:
        rel = spec.path.relative_to(specs_dir).as_posix()
        lines.append(f"- [`{spec.id}`]({rel}) — {spec.title} _(orphan: unknown parent)_")

    return "\n".join(lines) or "_No specs yet._"


def render_routes(specs: list[Spec], specs_dir: Path) -> str:
    # See render_tree: links are relative to specs_dir, where INDEX.md itself lives.
    def link(spec: Spec) -> str:
        return f"[`{spec.id}`]({spec.path.relative_to(specs_dir).as_posix()})"

    rows: list[tuple[str, str, str | None]] = [(p, link(s), s.parent) for s in specs for p in s.owns]
    rows.sort(key=lambda r: glob_specificity(r[0]), reverse=True)

    if not rows:
        return "_No spec declares an `owns` glob yet._"

    out = ["| Code path | Spec | Parent |", "|---|---|---|"]
    for pattern, cell, parent in rows:
        parent_cell = f"`{parent}`" if parent else "—"
        out.append(f"| `{pattern}` | {cell} | {parent_cell} |")
    return "\n".join(out)


def spec_order(specs: list[Spec], specs_dir: Path) -> tuple[list[Spec], dict[str, str]]:
    """The tree's own reading order (root first, then depth), plus each spec's link target.

    Cross-cutting decisions in the architecture spec then sit above the feature-scoped ones that
    assume them.
    """
    by_id = {s.id: s for s in specs}
    depth_of: dict[str, int] = {}

    def depth(spec: Spec) -> int:
        if spec.id not in depth_of:
            seen: set[str] = set()
            d, cursor = 0, spec.parent
            while cursor and cursor in by_id and cursor not in seen:
                seen.add(cursor)
                d += 1
                cursor = by_id[cursor].parent
            depth_of[spec.id] = d
        return depth_of[spec.id]

    ordered = sorted(specs, key=lambda s: (depth(s), s.path.name))
    return ordered, {s.id: s.path.relative_to(specs_dir).as_posix() for s in specs}


def render_decisions(specs: list[Spec], specs_dir: Path, problems: list[str], open_count: int) -> str:
    ordered, link = spec_order(specs, specs_dir)

    def cell(decision: Decision) -> str:
        # Notes that change whether a decision still binds belong next to it, not in a footnote.
        notes = []
        if decision.revisit_when:
            notes.append(f"⟳ revisit when {decision.revisit_when}")
        if decision.replaced:
            when = f" {decision.replaced_date}" if decision.replaced_date else ""
            notes.append(f"↩ replaced{when}: {decision.replaced}")
        return "<br>".join([decision.text] + [f"_{n}_" for n in notes])

    # One section per spec, so a task reads the specs it touches rather than the whole tree.
    def group(heading: str, decisions: list[Decision]) -> str:
        rows = [f"| {cell(d)} | {d.instead_of or '—'} | {d.because or '—'} |" for d in decisions]
        return "\n".join([heading, "", "| Decision | Instead of | Because |", "|---|---|---|"] + rows)

    groups = [group(f"### [`{s.id}`]({link[s.id]})", s.decisions) for s in ordered if s.decisions]
    decisions = "\n\n".join(groups) if groups else "_No decisions recorded yet._"

    hygiene = (
        "\n## Needs attention\n\nInformational — each needs a human read, none fails `--check`.\n\n"
        + "\n".join(f"- {p}" for p in problems)
        + "\n"
        if problems
        else ""
    )

    open_pointer = (
        f"{open_count} question(s) are still open: [`OPEN-QUESTIONS.md`](OPEN-QUESTIONS.md)."
        if open_count
        else "No open questions anywhere in the tree."
    )

    return f"""{HEADER}

# Decisions

Every decision in the spec tree, and what each one rejected, one section per spec in tree order. A
spec's own Decisions come with reading it; read the sections for its parent chain and `related`
specs here. Generated — edit the owning spec, not this file.

## Decisions

{decisions}

{open_pointer}
{hygiene}"""


def render_questions(specs: list[Spec], specs_dir: Path) -> str:
    """The other half of what the code can't tell you, kept separate because it's read differently.

    A decision binds anyone proposing anything nearby. An open question binds whoever touches the
    spec that holds it — and a spec's own questions already come with reading it, so this file is
    the view across the tree, grouped by spec so it stays readable as coverage grows.
    """
    ordered, link = spec_order(specs, specs_dir)

    def group(heading: str, questions: list[OpenQuestion]) -> str:
        rows = [f"| {q.text} | {q.action or '—'} |" for q in questions]
        return "\n".join([heading, "", "| Question | Action |", "|---|---|"] + rows)

    groups = []
    for s in ordered:
        still_open = [q for q in s.questions if not q.resolved]
        if still_open:
            groups.append(group(f"## [`{s.id}`]({link[s.id]})", still_open))
    questions = "\n\n".join(groups) if groups else "_Nothing open._"

    resolved_count = sum(1 for s in specs for q in s.questions if q.resolved)
    resolved_note = (
        f"\n\n{resolved_count} answered question(s) are still in their specs and not listed here; "
        f"delete them."
        if resolved_count
        else ""
    )

    return f"""{HEADER}

# Open questions

Every unresolved question in the spec tree, one section per spec. A spec's own questions come with
reading it — this is the view across the tree. Generated — edit the owning spec, not this file.

{questions}{resolved_note}
"""


def summarise_gaps(gaps: list[str]) -> str:
    """The area names alone. The uncovered files under each are the skill's output."""
    return ", ".join(f"`{g.split(chr(39))[1]}`" if "'" in g else f"`{g}`" for g in gaps)


def render_index(
    specs: list[Spec],
    changes: list[Change],
    errors: list[str],
    gaps: list[str],
    stale_specs: list[str],
    specs_dir: Path,
) -> str:
    drift = (
        "\n".join(f"- {e}" for e in errors)
        if errors
        else "_None. Every spec resolves and no ownership is ambiguous._"
    )
    # The gaps are summarised, not listed. This file is read on every task for routing, and the
    # list isn't routing data — it's a work queue, which `spec-rebuild-overviews` already prints in
    # full every time it runs.
    coverage = (
        f"{len(gaps)} area(s) have no owning spec yet — normal.\n\n"
        f"{summarise_gaps(gaps)}"
        if gaps
        else "_Everything is covered._"
    )
    freshness = (
        f"{len(stale_specs)} spec(s) own code that has been committed to since the spec itself was "
        f"last confirmed. A prompt to check, not a defect — code moves without intent moving. "
        f"`spec-sync-with-code` can confirm one: a clean check bumps `updated:`, anything else shows here "
        f"as its last result.\n\n"
        + "\n".join(f"- {s}" for s in stale_specs)
        if stale_specs
        else "_Every spec with an `owns` glob is at least as recent as the code under it._"
    )
    return f"""{HEADER}

# Spec index

Code path to owning spec, most specific glob first: the first row matching your file is the owner.

A file matching nothing has no owning spec — normal here; see "Not yet specced" below.

## Code → spec

{render_routes(specs, specs_dir)}

## Pending changes

{render_pending(changes, specs_dir)}

## Spec tree

{render_tree(specs, specs_dir)}

## Drift

Structural problems, and the only findings serious enough to stop an automated check: a spec with
no `id` or `title`, a dangling `owns` glob, an unknown `parent`, a duplicate id, two specs claiming
one file, a parent cycle. Empty is the normal state.

Everything else `spec-rebuild-overviews` notices — a stale spec, a coverage gap, a warning — it
reports and does not fail on.

{drift}

## Possibly stale

{freshness}

## Not yet specced

{coverage}

Also generated: [`DECISIONS.md`](DECISIONS.md), [`OPEN-QUESTIONS.md`](OPEN-QUESTIONS.md).
"""


