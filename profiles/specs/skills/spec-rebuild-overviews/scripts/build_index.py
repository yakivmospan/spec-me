#!/usr/bin/env python3
"""Rebuild .specs/INDEX.md, DECISIONS.md and OPEN-QUESTIONS.md from the spec tree, report drift.

Stdlib only — no pyyaml, no install step. Handles the subset of YAML the spec
frontmatter contract uses: scalars, inline lists, and block lists.

Three generated files, answering three questions, deliberately separate because they are read at
different moments and a reader shouldn't pay for the ones they don't need:

INDEX.md is a routing table: code path -> owning spec. Read every session, so everything in it is
what you need *to route* — coverage gaps appear only as a summary, with the item-by-item list
left to this script's own stdout.

DECISIONS.md aggregates what was decided and what lost. Read before proposing an approach: a
decision's rejected alternatives leave no trace in the source, so this is content no amount of
code reading recovers, and it is scattered one entry at a time at the bottom of whichever spec
owns the file. INDEX.md can't route anyone to it, because a decision often isn't about a code path.

OPEN-QUESTIONS.md holds what nobody has decided yet — the other thing missing from the code, but
scoped to whoever touches the spec that raised it rather than to every task, and typically the
faster-growing of the two.

All three are helpers: when one disagrees with the specs, the specs win.

Specs have no `status`; one still carrying it gets a warning.

Open changes under `.specs/changes/` are read too. Any folder there directly holding an
`implementation-plan.md` is a change, at any depth — nesting only groups, and a folder can be a change
and hold changes. Specs never move into a change: they stay in `.specs/` and are updated in place as
the work is built. The plan's frontmatter `status:` is `draft` or `approved` (missing reads as draft,
with a warning); its numbered checkboxes under `## Tasks` are counted. INDEX.md lists open changes
with their status and tasks done. A `specs.<path>.md` file left in a change folder from the old
process is warned about and never read as a spec.

A spec's `## Behaviour` is one bullet per rule. The rules themselves are never checked here: the
tests are their proof, found through `owns`.

Usage:
    python3 build_index.py [--specs-dir .specs] [--repo-root <path>] [--check]

--check exits 1 only on structural drift: a file with no frontmatter or no `id`/`title`, no single
root spec, a dangling `owns` glob, an unknown `parent`/`related`, a duplicate id, ambiguous ownership
and a parent cycle. Everything else — warnings, out-of-date generated files, coverage gaps,
possibly-stale specs — is reported and never fails: the generated files are kept out of git.
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

# Directories never reported as "unowned". Build output, tooling, and the agent setup itself.
# Skipping only affects unowned-reporting — routing is unaffected either way.
SKIP_DIRS = {
    "node_modules", "build", "dist", "out", "target", "vendor", "__pycache__", "venv", "coverage",
    # Not source: the Gradle wrapper and prebuilt `.aar`/`.jar` drops. A spec can own behaviour, not a
    # binary, so reporting these as uncovered only adds noise. Dot folders are skipped wherever this is.
    "gradle", "libs",
}

# This script's own output. Never parsed as specs — they have no frontmatter, and reading them
# back in would report each one as a malformed spec.
GENERATED = {"INDEX.md", "DECISIONS.md", "OPEN-QUESTIONS.md"}
# Markdown under `.specs/` that isn't a spec.
NOT_SPECS = GENERATED | {"README.md"}
# A manual test plan kept beside the spec it tests: `<spec>.manual-test-plan.md`.
TEST_PLAN_SUFFIX = ".manual-test-plan.md"

HEADER = """<!-- Generated by spec-rebuild-overviews — regenerate rather than edit; when this disagrees with the specs, the specs win. -->
<!-- Regenerate: python3 .agents/skills/spec-rebuild-overviews/scripts/build_index.py -->"""

# Open changes live here. Parsed by load_changes, never as specs.
CHANGES = "changes"
# A spec file the old process moved into a change, named after its place: `specs.feature.logger.md`.
LEFTOVER_SPEC = re.compile(r"^specs\.(.+)\.md$")
PLAN_STATUSES = ("draft", "approved")


@dataclass
class Decision:
    """One entry under a spec's `## Decisions`, parsed into its labelled sub-bullets.

    The shape is spec-style-rules' *What was rejected*'s: a bolded choice, then `Instead of` / `Because` /
    `Revisit when` / `Replaced {date}:` as sub-bullets. `instead_of` is the one that carries the
    information the code can't show — an entry missing it usually isn't a decision at all, which
    is why it's reported rather than quietly rendered blank.
    """
    text: str
    instead_of: str = ""
    because: str = ""
    revisit_when: str = ""
    replaced: str = ""
    replaced_date: str = ""


@dataclass
class OpenQuestion:
    text: str
    action: str
    resolved: bool = False


@dataclass
class Spec:
    path: Path
    id: str
    title: str
    parent: str | None
    owns: list[str] = field(default_factory=list)
    related: list[str] = field(default_factory=list)
    updated: str = ""
    decisions: list[Decision] = field(default_factory=list)
    questions: list[OpenQuestion] = field(default_factory=list)
    # Change history rows too long to be one sentence, as "ticket date (n words)".
    long_history_rows: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------- parsing


def split_frontmatter(text: str) -> str | None:
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end == -1:
        return None
    return text[3:end]


def unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_frontmatter(block: str) -> dict[str, object]:
    """Minimal YAML: `key: scalar`, `key: [a, b]`, and block lists under `key:`."""
    data: dict[str, object] = {}
    current_key: str | None = None

    for raw in block.splitlines():
        line = re.sub(r"""^((?:[^#"']|"[^"]*"|'[^']*')*?)\s+#.*$""", r"\1", raw.rstrip())  # an inline `# comment`
        if not line.strip() or line.strip().startswith("#"):
            continue

        stripped = line.lstrip()
        indented = len(line) - len(stripped)

        if stripped.startswith("- ") and current_key and indented > 0:
            data.setdefault(current_key, [])
            target = data[current_key]
            if isinstance(target, list):
                target.append(unquote(stripped[2:]))
            continue

        if ":" not in stripped:
            continue

        key, _, value = stripped.partition(":")
        key = key.strip()
        value = value.strip()
        current_key = key

        if not value:
            data[key] = []
        elif value.startswith("[") and value.endswith("]"):
            inner = value[1:-1].strip()
            data[key] = [unquote(p) for p in inner.split(",") if p.strip()] if inner else []
        else:
            data[key] = unquote(value)

    return data


def as_list(value: object) -> list[str]:
    if isinstance(value, list):
        return [str(v) for v in value if str(v).strip()]
    if isinstance(value, str) and value.strip() and value.strip() != "[]":
        return [value.strip()]
    return []


def scalar(value: object) -> str:
    """A frontmatter value as a string; an empty `key:` parses as [] and reads as ""."""
    return value.strip() if isinstance(value, str) else ""


def parent_of(meta: dict[str, object]) -> str | None:
    parent = meta.get("parent")
    return None if parent in (None, "", "null", "~", []) else str(parent)


BOLD = re.compile(r"\*\*(.+?)\*\*", re.DOTALL)
ACTION = re.compile(r"\*\*Action:\*\*\s*(.*)", re.DOTALL)


def squash(text: str) -> str:
    """Collapse a multi-line markdown span into one line, dropping list/emphasis punctuation."""
    return " ".join(text.replace("~~", "").split()).strip(" —-–")


def body_after_frontmatter(text: str) -> str:
    if not text.startswith("---"):
        return text
    end = text.find("\n---", 3)
    return text[end + 4:] if end != -1 else text


def extract_section(body: str, heading: str) -> str:
    """The lines under a `## heading`, up to the next heading of the same or higher level."""
    lines = body.splitlines()
    wanted = heading.strip().lower()
    out: list[str] = []
    collecting = False

    for line in lines:
        if line.startswith("## "):
            if collecting:
                break
            collecting = line[3:].strip().lower() == wanted
            continue
        if line.startswith("# ") and collecting:
            break
        if collecting:
            out.append(line)

    return "\n".join(out)


def iter_entries(section: str) -> list[str]:
    """Top-level `- ` bullets, each joined with its indented continuation lines.

    A decision or an open question routinely wraps across several lines, and its bolded span can
    wrap with it — so entries have to be reassembled before anything can be matched against them.
    """
    entries: list[str] = []
    current: list[str] = []

    for line in section.splitlines():
        starts_entry = line.startswith("- ")
        if starts_entry:
            if current:
                entries.append("\n".join(current))
            current = [line[2:]]
        elif current and (not line.strip() or line.startswith((" ", "\t"))):
            current.append(line)
        elif current:
            entries.append("\n".join(current))
            current = []

    if current:
        entries.append("\n".join(current))

    return [e for e in entries if e.strip()]


SUBFIELD = re.compile(r"^\s+-\s*\*\*(.+?)\*\*\s*(.*)$")


def split_fields(entry: str) -> tuple[str, dict[str, str]]:
    """Split an entry into its headline and its labelled sub-bullets.

    Both the headline and a field's value can wrap across lines, so this tracks which one is
    currently open rather than assuming one line each.
    """
    head: list[str] = []
    fields: dict[str, str] = {}
    label: str | None = None
    buf: list[str] = []

    for line in entry.splitlines():
        match = SUBFIELD.match(line)
        if match:
            if label is not None:
                fields[label] = squash(" ".join(buf))
            label = match.group(1).strip().rstrip(":").lower()
            buf = [match.group(2)]
        elif label is not None:
            buf.append(line)
        else:
            head.append(line)

    if label is not None:
        fields[label] = squash(" ".join(buf))

    bold = BOLD.search("\n".join(head))
    headline = squash(bold.group(1)) if bold else squash("\n".join(head))
    return headline, fields


def parse_decisions(body: str) -> list[Decision]:
    out: list[Decision] = []
    for entry in iter_entries(extract_section(body, "Decisions")):
        text, fields = split_fields(entry)
        if not text:
            continue

        # `Replaced` carries its date inside the label (`**Replaced 2026-09-10:**`), so the key
        # varies per entry and can't be looked up directly.
        replaced_key = next((k for k in fields if k.startswith("replaced")), "")
        replaced_date = replaced_key[len("replaced"):].strip() if replaced_key else ""

        out.append(
            Decision(
                text=text,
                instead_of=fields.get("instead of", ""),
                because=fields.get("because", ""),
                revisit_when=fields.get("revisit when", ""),
                replaced=fields.get(replaced_key, "") if replaced_key else "",
                replaced_date=replaced_date,
            )
        )
    return out


def parse_open_questions(body: str) -> list[OpenQuestion]:
    out: list[OpenQuestion] = []
    for entry in iter_entries(extract_section(body, "Open questions")):
        stripped = entry.lstrip()
        # An answered question is deleted; a `[x]` one left over from the old checkbox format still counts as answered.
        checkbox = stripped.startswith("[")
        if not checkbox and not stripped.startswith("**"):
            continue
        resolved = stripped[:3].lower() == "[x]"
        match = BOLD.search(entry)
        text = squash(match.group(1)) if match else squash(stripped[3:] if checkbox else stripped)
        action_match = ACTION.search(entry)
        action = squash(action_match.group(1)) if action_match else ""
        if text:
            out.append(
                OpenQuestion(text=text, action=action, resolved=resolved)
            )
    return out


# spec-style-rules' *One row, one sentence*. Past this, a row is almost always a root-cause write-up or
# an investigation log rather than a statement of what changed.
HISTORY_ROW_WORDS = 35


def parse_long_history_rows(body: str) -> list[str]:
    """Change history rows whose Change cell runs past what one sentence needs.

    The style rule broken most often in practice, and the only one a word count can see.
    Informational: a long row misleads nobody, it taxes every reader.
    """
    out: list[str] = []
    for line in extract_section(body, "Change history").splitlines():
        if not line.strip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or set(cells[1]) <= set("-: ") or cells[1].lower() == "change":
            continue
        words = len(cells[1].split())
        if words > HISTORY_ROW_WORDS:
            out.append(f"{cells[0]} {cells[-1]} ({words} words)")
    return out


def load_specs(specs_dir: Path) -> tuple[list[Spec], list[str], list[str]]:
    """Every spec under `.specs/` outside `changes/`, plus (drift, warnings) found reading them."""
    specs: list[Spec] = []
    problems: list[str] = []
    warnings: list[str] = []

    for path in sorted(specs_dir.rglob("*.md")):
        if (path.name in NOT_SPECS or path.name.endswith(TEST_PLAN_SUFFIX)
                or path.relative_to(specs_dir).parts[0] == CHANGES):
            continue

        text = path.read_text(encoding="utf-8")
        block = split_frontmatter(text)
        rel = path.relative_to(specs_dir.parent).as_posix()

        if block is None:
            problems.append(f"{rel}: no frontmatter block — every spec needs one")
            continue

        meta = parse_frontmatter(block)
        missing = [k for k in ("id", "title") if not meta.get(k)]
        if missing:
            problems.append(f"{rel}: frontmatter missing required key(s): {', '.join(missing)}")
            continue
        if "status" in meta:
            warnings.append(f"{rel}: `status` is no longer used — delete the line")

        spec_id = str(meta["id"])
        body = body_after_frontmatter(text)

        specs.append(
            Spec(
                path=path,
                id=spec_id,
                title=str(meta["title"]),
                parent=parent_of(meta),
                owns=as_list(meta.get("owns")),
                related=as_list(meta.get("related")),
                updated=scalar(meta.get("updated")),
                decisions=parse_decisions(body),
                questions=parse_open_questions(body),
                long_history_rows=parse_long_history_rows(body),
            )
        )

    return specs, problems, warnings


# --------------------------------------------------------------------------- changes

@dataclass
class Task:
    title: str
    done: bool


@dataclass(eq=False)
class Change:
    """A folder under `.specs/changes/` directly holding an `implementation-plan.md`."""
    path: Path
    name: str
    # The plan's `status:` — `draft` or `approved`; anything else reads as draft.
    plan_status: str = "draft"
    tasks: list[Task] = field(default_factory=list)
    # The nearest enclosing change folder, when nested — for display only.
    parent: Change | None = field(default=None, repr=False)

    @property
    def approved(self) -> bool:
        return self.plan_status == "approved"

    def status(self) -> str:
        return "Approved" if self.approved else "Draft"

    def tasks_all_done(self) -> bool:
        return bool(self.tasks) and all(t.done for t in self.tasks)

    def link(self, specs_dir: Path) -> str:
        return self.path.relative_to(specs_dir).as_posix() + "/"


PLAN = "implementation-plan.md"
# `- [ ] **3. …**`, the number inside the bold title; `3. [ ] **…**` is the older shape, still read.
TASK_LINE = re.compile(r"^(?:-\s+\[([ xX])\](?=\s+\*\*\d+\.)|\d+\.\s+\[([ xX])\])\s+(.*)$")


def parse_tasks(change: Change, text: str) -> None:
    """Numbered checkboxes under `## Tasks`. A task's headline may wrap onto indented lines; its
    `- Check:` sub-bullets and `>` notes aren't part of it."""
    body = body_after_frontmatter(text)
    section = extract_section(body, "Tasks") or body
    entries: list[tuple[bool, list[str]]] = []
    in_headline = False
    for line in section.splitlines():
        match = TASK_LINE.match(line)
        if match:
            box = match.group(1) or match.group(2)
            entries.append((box.lower() == "x", [match.group(3)]))
            in_headline = True
        elif not in_headline:
            continue
        elif line.startswith((" ", "\t")) and line.strip() and not line.strip().startswith(("-", ">")):
            entries[-1][1].append(line.strip())
        else:
            in_headline = False
    for done, headline in entries:
        change.tasks.append(Task(title=squash(" ".join(headline)), done=done))


def load_change(folder: Path, root: Path, repo_root: Path, warnings: list[str]) -> Change:
    change = Change(path=folder, name=folder.relative_to(root).as_posix())
    plan = folder / PLAN
    text = plan.read_text(encoding="utf-8")
    status = scalar(parse_frontmatter(split_frontmatter(text) or "").get("status"))
    where = plan.relative_to(repo_root).as_posix()
    if not status:
        warnings.append(f"{where}: no status — add `status: draft`")
    elif status not in PLAN_STATUSES:
        warnings.append(f"{where}: unknown status `{status}` — use `draft` or `approved`")
    else:
        change.plan_status = status
    parse_tasks(change, text)
    return change


def load_changes(specs_dir: Path, repo_root: Path) -> tuple[list[Change], list[str]]:
    """Every open change, in folder order, plus warnings about change folders.

    A change is a folder directly holding an `implementation-plan.md`; any other folder only groups.
    """
    root = specs_dir / CHANGES
    if not root.is_dir():
        return [], []
    changes: list[Change] = []
    warnings: list[str] = []

    def walk(folder: Path, enclosing: Change | None) -> None:
        current = enclosing
        if folder != root and (folder / PLAN).is_file():
            current = load_change(folder, root, repo_root, warnings)
            current.parent = enclosing
            changes.append(current)
        for leftover in sorted(p for p in folder.glob("specs.*.md") if p.is_file()):
            place = LEFTOVER_SPEC.match(leftover.name).group(1).replace(".", "/") + ".md"
            warnings.append(f"{leftover.relative_to(repo_root).as_posix()}: specs no longer move into "
                            f"a change — move it back to `.specs/{place}`")
        for sub in sorted(p for p in folder.iterdir() if p.is_dir()):
            walk(sub, current)

    walk(root, None)
    return changes, warnings


def change_label(change: Change) -> str:
    """Top-level changes by name; a nested one by its path under the change enclosing it, indented."""
    if change.parent is None:
        return f"`{change.name}`"
    depth, cursor = 0, change.parent
    while cursor is not None:
        depth, cursor = depth + 1, cursor.parent
    return "&nbsp;&nbsp;" * (depth - 1) + f"↳ `{change.path.relative_to(change.parent.path).as_posix()}`"


def render_pending(changes: list[Change], specs_dir: Path) -> str:
    if not changes:
        return "_No open changes._"
    out = [
        "Work planned or being built. Specs stay in `.specs/` and are updated in place as tasks are "
        "built; read a change's `implementation-plan.md` only when building it. Status comes from the "
        "plan's `status:`.",
        "",
        "| Change | Status | Tasks done |",
        "|---|---|---|",
    ]
    for change in changes:
        done = f"{sum(t.done for t in change.tasks)}/{len(change.tasks)}" if change.tasks else "—"
        out.append(f"| [{change_label(change)}]({change.link(specs_dir)}) | {change.status()} | {done} |")
    return "\n".join(out)


# --------------------------------------------------------------------------- checks


def glob_specificity(pattern: str) -> tuple[int, int]:
    """Higher sorts first. Fewer wildcards and more path segments = more specific."""
    return (-pattern.count("*") - 2 * pattern.count("**"), pattern.count("/"))


def iter_files(root: Path):
    """Yield every file under root, pruning SKIP_DIRS and dotdirs without descending into them."""
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for name in filenames:
            yield Path(dirpath) / name


def find_gaps(specs: list[Spec], repo_root: Path, max_depth: int = 4) -> list[str]:
    """Directories with zero spec coverage, found by actually checking which files match an
    `owns` glob — not by comparing directory name prefixes, which hides gaps nested under a
    directory that's only partially covered (e.g. `src/checkout/**` owned doesn't mean the rest
    of `src/` is; every sibling under `src/` needs checking individually).

    A directory with no coverage at all is reported and not descended into further (the whole
    subtree is the gap). A directory that's fully covered is skipped. A directory that's a mix
    gets descended into, to find exactly which subdirectories are the actual gap.
    """
    owned_patterns = [p for s in specs for p in s.owns]

    def covered(file_path: Path) -> bool:
        rel = file_path.relative_to(repo_root).as_posix()
        return any(fnmatch.fnmatch(rel, pat) for pat in owned_patterns)

    gaps: list[str] = []

    def classify(dir_path: Path, depth: int) -> None:
        rel_dir = dir_path.relative_to(repo_root).as_posix()
        all_files = list(iter_files(dir_path))
        if not all_files:
            return  # empty directory — nothing to own, nothing to report

        covered_count = sum(1 for f in all_files if covered(f))
        if covered_count == 0:
            gaps.append(f"'{rel_dir}/' has no owning spec yet")
            return
        if covered_count == len(all_files):
            return  # fully covered

        # Partially covered — descend to isolate the actual gap, unless we've gone deep enough
        # that further drilling stops being useful.
        if depth >= max_depth:
            gaps.append(f"'{rel_dir}/' is partially covered — check its subdirectories")
            return

        try:
            subdirs = sorted(
                e for e in dir_path.iterdir()
                if e.is_dir() and e.name not in SKIP_DIRS and not e.name.startswith(".")
            )
            loose_files = [e for e in dir_path.iterdir() if e.is_file()]
        except OSError:
            return

        for sub in subdirs:
            classify(sub, depth + 1)

        uncovered_loose = [f for f in loose_files if not covered(f)]
        if uncovered_loose:
            names = ", ".join(f.name for f in sorted(uncovered_loose)[:3])
            more = f" (+{len(uncovered_loose) - 3} more)" if len(uncovered_loose) > 3 else ""
            gaps.append(f"'{rel_dir}/' has uncovered file(s): {names}{more}")

    for child in sorted(repo_root.iterdir()):
        if child.is_dir() and not child.name.startswith(".") and child.name not in SKIP_DIRS:
            classify(child, 1)

    return gaps


# Above this, two decisions in different specs are near-certainly the same decision written twice.
# Tuned to catch rewordings ("Version negotiation stays in X, not in the API module" vs
# "Version-negotiation semantics stay in X, not here") without flagging two decisions that merely
# discuss the same module.
DUPLICATE_RATIO = 0.6


def find_decision_problems(specs: list[Spec]) -> list[str]:
    """Decisions that aren't decisions, and decisions owned by two specs at once.

    Both are informational. "No `Instead of`" is a strong hint the entry is really a Behaviour rule
    or a scope note, but judging that needs a human read. Duplication is a similarity heuristic, and
    the fix (which spec should own it) is never mechanical.
    """
    import difflib

    out: list[str] = []
    flat = [(s, d) for s in specs for d in s.decisions]

    for spec, decision in flat:
        if not decision.instead_of:
            rel = spec.path.name
            out.append(
                f"{rel}: \"{decision.text[:70]}\" has no `Instead of` — if nothing was rejected, "
                f"this is a Behaviour rule or a scope note, not a decision"
            )

    for i, (spec_a, dec_a) in enumerate(flat):
        for spec_b, dec_b in flat[i + 1:]:
            if spec_a.id == spec_b.id:
                continue
            ratio = difflib.SequenceMatcher(None, dec_a.text.lower(), dec_b.text.lower()).ratio()
            if ratio >= DUPLICATE_RATIO:
                out.append(
                    f"same decision in two specs ({ratio:.0%} similar): `{spec_a.id}` and "
                    f"`{spec_b.id}` both state \"{dec_a.text[:60]}\" — one spec owns it, the "
                    f"other links"
                )

    return out


SPEC_CHECKS = Path(".agents") / ".cache" / "spec-checks.json"


def load_spec_checks(repo_root: Path) -> dict[str, dict]:
    """The last `spec-sync-with-code` run per spec id, recorded by its `record_check.py` — {} when there's none."""
    path = repo_root / SPEC_CHECKS
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def check_note(check: dict | None) -> str:
    """` — last checked 2026-09-14: tests 46/47 passed; differs: retry count`, or "" with no check recorded."""
    if not isinstance(check, dict):
        return ""
    passed, failed = int(check.get("passed") or 0), int(check.get("failed") or 0)
    parts = [f"tests {passed}/{passed + failed} passed"] if passed + failed else ["no tests run"]
    if check.get("differs"):
        parts.append("differs: " + ", ".join(check["differs"]))
    if check.get("cant_tell"):
        parts.append("can't tell: " + ", ".join(check["cant_tell"]))
    if not check.get("differs") and not check.get("cant_tell"):
        parts.append("reading holds")
    return f" — last checked {check.get('date', '?')}: " + "; ".join(parts)


def find_stale(specs: list[Spec], repo_root: Path) -> list[str]:
    """Specs whose owned code has moved on since the spec last did.

    AGENTS.md opens with "specs hold intent, code holds behaviour, when they disagree stop and
    reconcile" — and nothing else in this toolchain could tell you they might. Everything else here
    checks a spec's structure. None of that notices a spec whose prose quietly stopped being true.

    `updated:` is read as "the day someone last confirmed this spec against its code", so the
    signal is commits to the owned globs dated after it. It's a prompt to look, never a failure:
    plenty of commits move code without moving intent, and a broad `owns` glob will surface often
    — which is itself worth knowing, since it usually means the spec is too broad or nobody has
    re-read it in a while. Returns [] when git can't answer, rather than guessing.
    """
    out: list[str] = []
    checks = load_spec_checks(repo_root)

    for spec in specs:
        if not spec.owns:
            continue
        note = check_note(checks.get(spec.id))
        rel = spec.path.relative_to(repo_root).as_posix()
        if not spec.updated:  # optional — nothing to judge staleness against
            continue

        command = [
            "git", "-C", str(repo_root), "log", "--format=%cd", "--date=short",
            # Strictly later days only: `updated:` has day granularity, so a spec confirmed the
            # same day as the commit it describes is current, not behind.
            f"--since={spec.updated} 23:59:59", "--",
            *(f":(glob){pattern}" for pattern in spec.owns),
        ]
        try:
            result = subprocess.run(command, capture_output=True, text=True, timeout=30)
        except (OSError, subprocess.SubprocessError):
            return out
        if result.returncode != 0:
            continue

        commits = [line for line in result.stdout.splitlines() if line.strip()]
        if commits:
            out.append(
                f"{rel}: {len(commits)} commit(s) to the code it owns since `updated: "
                f"{spec.updated}` (latest {commits[0]}) — `spec-sync-with-code` can confirm it{note}"
            )

    return out


def validate(
    specs: list[Spec], repo_root: Path
) -> tuple[list[str], list[str], list[str], list[str]]:
    """Returns (errors, gaps, decision_problems, stale).

    Errors are structural: a dangling glob, a duplicate id, a cycle, ambiguous ownership. These
    drive --check's exit code. Everything else is informational — gaps especially: "no spec here
    yet" is the normal state of most of a pre-existing codebase, and coverage grows one task at a time.
    """
    errors: list[str] = []
    by_id: dict[str, Spec] = {}

    for spec in specs:
        rel = spec.path.relative_to(repo_root).as_posix()
        if spec.id in by_id:
            other = by_id[spec.id].path.relative_to(repo_root).as_posix()
            errors.append(f"duplicate id '{spec.id}': {rel} and {other}")
        else:
            by_id[spec.id] = spec

    roots = [s for s in specs if s.parent is None]
    if len(roots) > 1:
        names = ", ".join(sorted(s.id for s in roots))
        errors.append(f"multiple root specs (parent: null): {names} — exactly one expected")
    if not roots and specs:
        errors.append("no root spec — one spec must have `parent: null`")

    known = set(by_id)
    for spec in specs:
        rel = spec.path.relative_to(repo_root).as_posix()

        if spec.parent and spec.parent not in known:
            errors.append(f"{rel}: parent '{spec.parent}' is not a known spec id")

        # `related` is a real pointer, not decoration — a dangling one sends a reader to a spec
        # that was never written, or was renamed without this reference following.
        for ref in spec.related:
            if ref not in known:
                errors.append(f"{rel}: related '{ref}' is not a known spec id")

        # cycle detection
        seen, cursor = {spec.id}, spec.parent
        while cursor and cursor in by_id:
            if cursor in seen:
                errors.append(f"{rel}: parent chain forms a cycle at '{cursor}'")
                break
            seen.add(cursor)
            cursor = by_id[cursor].parent

        for pattern in spec.owns:
            if not any(repo_root.glob(pattern)):
                errors.append(f"{rel}: owns '{pattern}' matches nothing on disk")

    # overlapping globs of identical specificity
    claims: list[tuple[str, Spec]] = [(p, s) for s in specs for p in s.owns]
    for i, (pattern_a, spec_a) in enumerate(claims):
        for pattern_b, spec_b in claims[i + 1:]:
            if spec_a.id == spec_b.id:
                continue
            if glob_specificity(pattern_a) != glob_specificity(pattern_b):
                continue
            overlap = set(repo_root.glob(pattern_a)) & set(repo_root.glob(pattern_b))
            if overlap:
                errors.append(
                    f"ambiguous ownership: '{pattern_a}' ({spec_a.id}) and "
                    f"'{pattern_b}' ({spec_b.id}) both claim the same files at equal specificity"
                )

    # unowned source — a gap, not an error. See find_gaps' docstring.
    gaps = find_gaps(specs, repo_root)

    return errors, gaps, find_decision_problems(specs), find_stale(specs, repo_root)


