def render_tree(specs: list[Spec], changes: list[Change], specs_dir: Path) -> str:
    # Links are relative to specs_dir, not repo_root: INDEX.md lives inside specs_dir, and a
    # markdown relative link resolves against the file that contains it, not the repo root.
    by_parent: dict[str | None, list[Spec]] = {}
    for spec in specs:
        by_parent.setdefault(spec.parent, []).append(spec)

    lines: list[str] = []

    def walk(parent: str | None, depth: int) -> None:
        for spec in sorted(by_parent.get(parent, []), key=lambda s: s.path.name):
            rel = spec.path.relative_to(specs_dir).as_posix()
            lines.append(f"{'  ' * depth}- [`{spec.id}`]({rel}) — {spec.title}")
            walk(spec.id, depth + 1)

    walk(None, 0)

    known = {s.id for s in specs}
    in_changes = {s.spec_id for c in changes for s in c.specs}
    orphans = [s for s in specs if s.parent and s.parent not in known]
    for spec in orphans:
        rel = spec.path.relative_to(specs_dir).as_posix()
        note = "parent in an open change" if spec.parent in in_changes else "orphan: unknown parent"
        lines.append(f"- [`{spec.id}`]({rel}) — {spec.title} _({note})_")

    return "\n".join(lines) or "_No specs yet._"


def render_routes(specs: list[Spec], changes: list[Change], specs_dir: Path) -> str:
    # See render_tree: links are relative to specs_dir, where INDEX.md itself lives.
    copies: dict[Path, list[str]] = {}
    for c in changes:
        for s in c.specs:
            if s.landing is not None:
                copies.setdefault(s.landing.path, []).append(
                    f"[`{c.path.name}`]({spec_file_link(c, s, specs_dir)})")

    def link(spec: Spec) -> str:
        own = f"[`{spec.id}`]({spec.path.relative_to(specs_dir).as_posix()})"
        return own + (f" (copy in {', '.join(copies[spec.path])})" if spec.path in copies else "")

    rows: list[tuple[str, str, str | None]] = [(p, link(s), s.parent) for s in specs for p in s.owns]
    # A spec in a change routes its code there until it is merged.
    rows += [
        (p, f"[`{s.spec_id}` (in a change)]({spec_file_link(c, s, specs_dir)})", s.parent)
        for c in changes for s in c.specs if s.new and s.spec_id for p in s.owns
    ]
    rows.sort(key=lambda r: glob_specificity(r[0]), reverse=True)

    if not rows:
        return "_No spec declares an `owns` glob yet._"

    out = ["| Code path | Spec | Parent |", "|---|---|---|"]
    for pattern, cell, parent in rows:
        parent_cell = f"`{parent}`" if parent else "—"
        out.append(f"| `{pattern}` | {cell} | {parent_cell} |")
    return "\n".join(out)


def spec_order(specs: list[Spec], specs_dir: Path) -> tuple[list[Spec], dict[str, str]]:
    """The tree's own reading order (root first, then depth), plus each spec's link target.

    Cross-cutting decisions in the architecture spec then sit above the feature-scoped ones that
    assume them.
    """
    by_id = {s.id: s for s in specs}
    depth_of: dict[str, int] = {}

    def depth(spec: Spec) -> int:
        if spec.id not in depth_of:
            seen: set[str] = set()
            d, cursor = 0, spec.parent
            while cursor and cursor in by_id and cursor not in seen:
                seen.add(cursor)
                d += 1
                cursor = by_id[cursor].parent
            depth_of[spec.id] = d
        return depth_of[spec.id]

    ordered = sorted(specs, key=lambda s: (depth(s), s.path.name))
    return ordered, {s.id: s.path.relative_to(specs_dir).as_posix() for s in specs}


def render_decisions(
    specs: list[Spec], changes: list[Change], specs_dir: Path, problems: list[str], open_count: int
) -> str:
    ordered, link = spec_order(specs, specs_dir)

    def cell(decision: Decision) -> str:
        # Notes that change whether a decision still binds belong next to it, not in a footnote.
        notes = []
        if decision.revisit_when:
            notes.append(f"⟳ revisit when {decision.revisit_when}")
        if decision.replaced:
            when = f" {decision.replaced_date}" if decision.replaced_date else ""
            notes.append(f"↩ replaced{when}: {decision.replaced}")
        return "<br>".join([decision.text] + [f"_{n}_" for n in notes])

    # One section per spec, so a task reads the specs it touches rather than the whole tree.
    def group(heading: str, decisions: list[Decision]) -> str:
        rows = [f"| {cell(d)} | {d.instead_of or '—'} | {d.because or '—'} |" for d in decisions]
        return "\n".join([heading, "", "| Decision | Instead of | Because |", "|---|---|---|"] + rows)

    groups = [group(f"### [`{s.id}`]({link[s.id]})", s.decisions) for s in ordered if s.decisions]
    decisions = "\n\n".join(groups) if groups else "_No decisions recorded yet._"

    pending_groups = [
        group(f"### `{s.spec_id or s.file}` — in [`changes/{c.name}`]({c.link(specs_dir)})",
              s.pending_decisions())
        for c in changes
        for s in c.specs
        if s.pending_decisions()
    ]
    # Not binding until merged, but the same "don't re-decide it" reason to read them applies.
    pending = (
        "\n\n## In open changes\n\nSpecs moved into a change, and new ones. A moved spec's decisions "
        "still bind; what the change adds binds once it merges, and is worth knowing before proposing "
        "anything in the same area.\n\n"
        + "\n\n".join(pending_groups)
        if pending_groups
        else ""
    )

    hygiene = (
        "\n## Needs attention\n\nInformational — each needs a human read, none fails `--check`.\n\n"
        + "\n".join(f"- {p}" for p in problems)
        + "\n"
        if problems
        else ""
    )

    open_pointer = (
        f"{open_count} question(s) are still open: [`OPEN-QUESTIONS.md`](OPEN-QUESTIONS.md)."
        if open_count
        else "No open questions anywhere in the tree."
    )

    return f"""{HEADER}

# Decisions

Every decision in the spec tree, and what each one rejected, one section per spec in tree order. A
spec's own Decisions come with reading it; read the sections for its parent chain and `related`
specs here. Generated — edit the owning spec, not this file.

## Decisions

{decisions}{pending}

{open_pointer}
{hygiene}"""


def render_questions(specs: list[Spec], changes: list[Change], specs_dir: Path) -> str:
    """The other half of what the code can't tell you, kept separate because it's read differently.

    A decision binds anyone proposing anything nearby. An open question binds whoever touches the
    spec that holds it — and a spec's own questions already come with reading it, so this file is
    the view across the tree, grouped by spec so it stays readable as coverage grows.
    """
    ordered, link = spec_order(specs, specs_dir)

    def group(heading: str, questions: list[OpenQuestion]) -> str:
        rows = [f"| {q.text} | {q.action or '—'} |" for q in questions]
        return "\n".join([heading, "", "| Question | Action |", "|---|---|"] + rows)

    groups = []
    for s in ordered:
        still_open = [q for q in s.questions if not q.resolved]
        if still_open:
            groups.append(group(f"## [`{s.id}`]({link[s.id]})", still_open))
    for c in changes:
        where = f"[`changes/{c.name}`]({c.link(specs_dir)})"
        for s in c.specs:
            if s.pending_questions():
                groups.append(group(f"## `{s.spec_id or s.file}` — in {where}", s.pending_questions()))
    questions = "\n\n".join(groups) if groups else "_Nothing open._"

    resolved_count = sum(1 for s in specs for q in s.questions if q.resolved)
    resolved_note = (
        f"\n\n{resolved_count} resolved question(s) are kept in place in their own specs, struck "
        f"through, and are not listed here."
        if resolved_count
        else ""
    )

    return f"""{HEADER}

# Open questions

Every unresolved question in the spec tree and in open changes, one section per spec. A spec's own
questions come with reading it —
this is the view across the tree. Generated — edit the owning spec or change, not this file.

{questions}{resolved_note}
"""


def summarise_gaps(gaps: list[str]) -> str:
    """The area names alone. The uncovered files under each are the skill's output."""
    return ", ".join(f"`{g.split(chr(39))[1]}`" if "'" in g else f"`{g}`" for g in gaps)


def render_index(
    specs: list[Spec],
    changes: list[Change],
    errors: list[str],
    gaps: list[str],
    stale_specs: list[str],
    specs_dir: Path,
) -> str:
    drift = (
        "\n".join(f"- {e}" for e in errors)
        if errors
        else "_None. Every spec resolves and no ownership is ambiguous._"
    )
    # Both lists below are summarised, not printed. This file is read on every task for routing,
    # and neither list is routing data — it's a work queue, which `spec-rebuild-overviews` already prints in
    # full every time it runs. The counts are what a reader needs at routing time: whether the
    # spec they are about to open is one of the affected ones.
    coverage = (
        f"{len(gaps)} area(s) have no owning spec yet — normal.\n\n"
        f"{summarise_gaps(gaps)}"
        if gaps
        else "_Everything is covered._"
    )
    freshness = (
        f"{len(stale_specs)} spec(s) own code that has been committed to since the spec itself was "
        f"last confirmed. A prompt to check, not a defect — code moves without intent moving. "
        f"`spec-sync-with-code` can confirm one: a clean check bumps `updated:`, anything else shows here "
        f"as its last result.\n\n"
        + "\n".join(f"- {s}" for s in stale_specs)
        if stale_specs
        else "_Every spec with an `owns` glob is at least as recent as the code under it._"
    )
    violated = {
        s.path.relative_to(specs_dir).as_posix(): len(s.violations) for s in specs if s.violations
    }
    violations = (
        f"{sum(violated.values())} constraint(s) recorded as currently violated. Each goes false "
        f"silently when the code is fixed — re-check it against the code before trusting it, and "
        f"remove it in the same change as the fix.\n\n"
        + ", ".join(f"`{p}` {n}" for p, n in sorted(violated.items()))
        + "\n\nRun `spec-rebuild-overviews` for the list."
        if violated
        else "_No constraint is recorded as currently violated._"
    )
    return f"""{HEADER}

# Spec index

Code path to owning spec, most specific glob first: the first row matching your file is the owner.
A spec in `changes/` is the version being worked on.

A file matching nothing has no owning spec — normal here; see "Not yet specced" below.

## Code → spec

{render_routes(specs, changes, specs_dir)}

## Pending changes

{render_pending(changes, specs_dir)}

## Spec tree

{render_tree(specs, changes, specs_dir)}

## Drift

Structural problems, and the only findings serious enough to stop an automated check: a spec with
no `id` or `title`, a dangling `owns` glob, an unknown `parent`, a duplicate id, two specs claiming
one file, a parent cycle. Empty is the normal state.

Everything else `spec-rebuild-overviews` notices — a stale spec, a coverage gap, a misplaced `status` — it
reports and does not fail on.

{drift}

## Possibly stale

{freshness}

## Known violations

{violations}

## Not yet specced

{coverage}

Also generated: [`DECISIONS.md`](DECISIONS.md), [`OPEN-QUESTIONS.md`](OPEN-QUESTIONS.md).
"""


# --------------------------------------------------------------------------- main


def find_repo_root() -> Path:
    """The folder holding `.agents/`, found from this script's own location, so it runs from anywhere."""
    for parent in Path(__file__).resolve().parents:
        if (parent / ".agents").is_dir():
            return parent
    return Path.cwd()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--specs-dir", default=".specs")
    parser.add_argument("--repo-root", type=Path, default=None)
    parser.add_argument("--check", action="store_true", help="exit 1 on structural drift only")
    args = parser.parse_args()

    repo_root = (args.repo_root or find_repo_root()).resolve()
    specs_dir = (repo_root / args.specs_dir).resolve()

    if not specs_dir.is_dir():
        print(f"error: {specs_dir} does not exist", file=sys.stderr)
        return 2

    specs, parse_errors, parse_warnings = load_specs(specs_dir)
    changes, change_folder_warnings = load_changes(specs_dir, specs)
    validation_errors, validation_warnings, gaps, decision_problems, stale_specs = validate(
        specs, changes, repo_root
    )
    errors = parse_errors + validation_errors
    warnings = parse_warnings + change_folder_warnings + validation_warnings

    open_count = (
        sum(1 for s in specs for q in s.questions if not q.resolved)
        + sum(len(s.pending_questions()) for c in changes for s in c.specs)
    )
    outputs = {
        specs_dir / "INDEX.md": render_index(
            specs, changes, errors, gaps, stale_specs, specs_dir
        ),
        specs_dir / "DECISIONS.md": render_decisions(
            specs, changes, specs_dir, decision_problems, open_count
        ),
        specs_dir / "OPEN-QUESTIONS.md": render_questions(specs, changes, specs_dir),
    }
    stale = [
        path for path, content in outputs.items()
        if (path.read_text(encoding="utf-8") if path.exists() else "") != content
    ]
    tasks_done = [c.name for c in changes if c.approved and c.tasks_all_done()]

    if args.check:
        # Only drift fails; everything below is informational. The generated files are kept out of git.
        for path in stale:
            print(f"({path.name} is out of date — run build_index.py; informational)", file=sys.stderr)
        for error in errors:
            print(f"drift: {error}", file=sys.stderr)
        for warning in warnings:
            print(f"warning: {warning}", file=sys.stderr)
        if gaps:
            print(f"({len(gaps)} area(s) not yet specced — informational, not a failure)",
                  file=sys.stderr)
        if stale_specs:
            print(f"({len(stale_specs)} spec(s) possibly stale — informational, not a failure)",
                  file=sys.stderr)
        n_violations = sum(len(s.violations) for s in specs)
        if n_violations:
            print(f"({n_violations} constraint(s) recorded as currently violated — informational)",
                  file=sys.stderr)
        if tasks_done:
            print(f"({len(tasks_done)} approved change(s) with every task done: {', '.join(tasks_done)} "
                  f"— merge once the user says it's done)", file=sys.stderr)
        n_long = sum(len(s.long_history_rows) for s in specs)
        if n_long:
            print(f"({n_long} Change history row(s) past {HISTORY_ROW_WORDS} words — "
                  f"informational)", file=sys.stderr)
        return 1 if errors else 0

    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
    written = ", ".join(p.name for p in outputs)
    print(f"wrote {written} — {len(specs)} spec(s), {len(changes)} open change(s)")
    for change in changes:
        hint = " — every task done: merge once the user says it's done" if change.name in tasks_done else ""
        print(f"  change {change.name}: {change.status()}{hint}")
    if errors:
        print(f"\n{len(errors)} drift item(s):")
        for error in errors:
            print(f"  - {error}")
    if warnings:
        print(f"\n{len(warnings)} warning(s) — none fails `--check`:")
        for warning in warnings:
            print(f"  - {warning}")
    if stale_specs:
        print(f"\n{len(stale_specs)} spec(s) possibly stale — code committed since the spec was "
              f"last confirmed:")
        for item in stale_specs:
            print(f"  - {item}")
    violations = [(s, v) for s in specs for v in s.violations]
    if violations:
        print(f"\n{len(violations)} constraint(s) recorded as currently violated — re-check each "
              f"against the code:")
        for spec, item in violations:
            print(f"  - {spec.path.relative_to(repo_root).as_posix()}: {item}")
    long_rows = [(s, r) for s in specs for r in s.long_history_rows]
    if long_rows:
        print(f"\n{len(long_rows)} Change history row(s) past {HISTORY_ROW_WORDS} words — rewrite "
              f"as one sentence (spec-style-rules' *One row, one sentence*):")
        for spec, row in long_rows:
            print(f"  - {spec.path.relative_to(repo_root).as_posix()}: {row}")
    if decision_problems:
        print(f"\n{len(decision_problems)} decision item(s) needing a human read:")
        for item in decision_problems:
            print(f"  - {item}")
    if gaps:
        print(f"\n{len(gaps)} area(s) not yet specced (informational, not a failure):")
        for gap in gaps:
            print(f"  - {gap}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
