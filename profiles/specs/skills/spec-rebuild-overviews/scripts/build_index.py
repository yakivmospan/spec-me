#!/usr/bin/env python3
"""Rebuild .specs/INDEX.md, DECISIONS.md and OPEN-QUESTIONS.md from the spec tree, report drift.

Stdlib only — no pyyaml, no install step. Handles the subset of YAML the spec
frontmatter contract uses: scalars, inline lists, and block lists.

Three generated files, answering three questions, deliberately separate because they are read at
different moments and a reader shouldn't pay for the ones they don't need:

INDEX.md is a routing table: code path -> owning spec. Read every session, so everything in it is
what you need *to route* — coverage gaps and violations appear only as counts, with the
item-by-item lists left to this script's own stdout.

DECISIONS.md aggregates what was decided and what lost. Read before proposing an approach: a
decision's rejected alternatives leave no trace in the source, so this is content no amount of
code reading recovers, and it is scattered one entry at a time at the bottom of whichever spec
owns the file. INDEX.md can't route anyone to it, because a decision often isn't about a code path.

OPEN-QUESTIONS.md holds what nobody has decided yet — the other thing missing from the code, but
scoped to whoever touches the spec that raised it rather than to every task, and typically the
faster-growing of the two.

All three are helpers: when one disagrees with the specs, the specs win.

Every spec has `status:` in its frontmatter: `draft` (not agreed yet), `approved` (agreed, OK to
build) or `merged` (describes the code as it is). Specs outside `changes/` are `merged`.

Open changes under `.specs/changes/` are read too. Any folder there directly holding a
`specs.<path>.md` file is a change, at any depth — nesting only groups, and a folder can be a change
and hold changes. Each `specs.<path>.md` is a whole spec as it should read afterwards, landing at
`.specs/<path>`: a new spec, or the spec moved there from `.specs/<path>` with `git mv`, edited — so
`.specs/<path>` itself is gone while the change is open. Approval is per spec file, by its `status:`;
a change is Draft, Approved, or Partly approved. Its `## Change` section is prose and never parsed.
INDEX.md lists open changes and routes a spec's code to the change holding it; DECISIONS.md and
OPEN-QUESTIONS.md include the specs in open changes.

A checkbox is a claim a person may make, and its proof sits under one `**Verified:**` sub-bullet: one
nested `**Source:**` per proof — a backticked test file with the test names declared in it nested
under it, or `Source: Manual` with an optional free description that is never read as test names.
Tests are welcome, never required. What doesn't line up is a warning: a checked box naming no proof,
proof under an unchecked one, and a listed test that doesn't resolve.

Usage:
    python3 build_index.py [--specs-dir .specs] [--repo-root <path>] [--check]

--check exits 1 only on structural drift: a file with no frontmatter or no `id`/`title`, no single
root spec, a dangling `owns` glob, an unknown `parent`/`related`, a duplicate id, ambiguous ownership,
a parent cycle, and a change spec file that can't land where it's named. Everything else — warnings
(a missing or misplaced `status` among them), out-of-date generated files, coverage gaps,
possibly-stale specs — is reported and never fails: the generated files are kept out of git.
"""

