def find_repo_root() -> Path:
    """The folder holding `.agents/`, found from this script's own location, so it runs from anywhere."""
    for parent in Path(__file__).resolve().parents:
        if (parent / ".agents").is_dir():
            return parent
    return Path.cwd()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--specs-dir", default=".specs")
    parser.add_argument("--repo-root", type=Path, default=None)
    parser.add_argument("--check", action="store_true", help="exit 1 on structural drift only")
    args = parser.parse_args()

    repo_root = (args.repo_root or find_repo_root()).resolve()
    specs_dir = (repo_root / args.specs_dir).resolve()

    if not specs_dir.is_dir():
        print(f"error: {specs_dir} does not exist", file=sys.stderr)
        return 2

    specs, parse_errors, parse_warnings = load_specs(specs_dir)
    changes, change_warnings = load_changes(specs_dir, repo_root)
    validation_errors, gaps, decision_problems, stale_specs = validate(specs, repo_root)
    errors = parse_errors + validation_errors
    warnings = parse_warnings + change_warnings

    open_count = sum(1 for s in specs for q in s.questions if not q.resolved)
    outputs = {
        specs_dir / "INDEX.md": render_index(
            specs, changes, errors, gaps, stale_specs, specs_dir
        ),
        specs_dir / "DECISIONS.md": render_decisions(specs, specs_dir, decision_problems, open_count),
        specs_dir / "OPEN-QUESTIONS.md": render_questions(specs, specs_dir),
    }
    stale = [
        path for path, content in outputs.items()
        if (path.read_text(encoding="utf-8") if path.exists() else "") != content
    ]
    tasks_done = [c.name for c in changes if c.approved and c.tasks_all_done()]

    if args.check:
        # Only drift fails; everything below is informational. The generated files are kept out of git.
        for path in stale:
            print(f"({path.name} is out of date — run build_index.py; informational)", file=sys.stderr)
        for error in errors:
            print(f"drift: {error}", file=sys.stderr)
        for warning in warnings:
            print(f"warning: {warning}", file=sys.stderr)
        if gaps:
            print(f"({len(gaps)} area(s) not yet specced — informational, not a failure)",
                  file=sys.stderr)
        if stale_specs:
            print(f"({len(stale_specs)} spec(s) possibly stale — informational, not a failure)",
                  file=sys.stderr)
        if tasks_done:
            print(f"({len(tasks_done)} approved change(s) with every task done: {', '.join(tasks_done)} "
                  f"— merge once the user says it's done)", file=sys.stderr)
        n_long = sum(len(s.long_history_rows) for s in specs)
        if n_long:
            print(f"({n_long} Change history row(s) past {HISTORY_ROW_WORDS} words — "
                  f"informational)", file=sys.stderr)
        return 1 if errors else 0

    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
    written = ", ".join(p.name for p in outputs)
    print(f"wrote {written} — {len(specs)} spec(s), {len(changes)} open change(s)")
    for change in changes:
        hint = " — every task done: merge once the user says it's done" if change.name in tasks_done else ""
        print(f"  change {change.name}: {change.status()}{hint}")
    if errors:
        print(f"\n{len(errors)} drift item(s):")
        for error in errors:
            print(f"  - {error}")
    if warnings:
        print(f"\n{len(warnings)} warning(s) — none fails `--check`:")
        for warning in warnings:
            print(f"  - {warning}")
    if stale_specs:
        print(f"\n{len(stale_specs)} spec(s) possibly stale — code committed since the spec was "
              f"last confirmed:")
        for item in stale_specs:
            print(f"  - {item}")
    long_rows = [(s, r) for s in specs for r in s.long_history_rows]
    if long_rows:
        print(f"\n{len(long_rows)} Change history row(s) past {HISTORY_ROW_WORDS} words — rewrite "
              f"as one sentence (spec-style-rules' *One row, one sentence*):")
        for spec, row in long_rows:
            print(f"  - {spec.path.relative_to(repo_root).as_posix()}: {row}")
    if decision_problems:
        print(f"\n{len(decision_problems)} decision item(s) needing a human read:")
        for item in decision_problems:
            print(f"  - {item}")
    if gaps:
        print(f"\n{len(gaps)} area(s) not yet specced (informational, not a failure):")
        for gap in gaps:
            print(f"  - {gap}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
